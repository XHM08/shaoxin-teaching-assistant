
import os
import sys

根 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, 根)

from 地基 import 工具箱, 配置
from 能力 import _授权, _命令
from 能力 import _对话工具

过, 失败 = [], []


def 记(条件, 说明):
    (过 if 条件 else 失败).append(说明)


执行过 = []


def _做(名字, 值):
    执行过.append((名字, 值))
    return {"回": 名字 + str(值)}


def 甲(值=""):
    return _做("甲", 值)


def 乙(值=""):
    return _做("乙", 值)


def 丙(值=""):
    return _做("丙", 值)


测名们 = ("甲", "乙", "丙")
占用了 = [名 for 名 in 测名们 if 名 in 工具箱.已登记工具]
if 占用了:
    print("跳过：测试工具名被占用（%s），本次不验多段连跑" % "、".join(占用了))
    sys.exit(3)

for 名, 函数 in (("甲", 甲), ("乙", 乙), ("丙", 丙)):
    工具箱.登记工具(名, "自检用", [{"代号": "值", "标签": "值"}], 函数)

三段 = (chr(10) + '{"工具": "甲", "参数": {"值": "1"}}' + chr(10)
        + '{"工具": "乙", "参数": {"值": "2"}}' + chr(10)
        + '{"工具": "丙", "参数": {"值": "3"}}' + chr(10))
两段 = chr(10).join(三段.strip().split(chr(10))[:2])

连跑文件 = os.path.join(配置.根目录, "_自检连跑.txt")
会话 = "自检-多段-连跑"

try:
    调用们 = 工具箱.找出调用(三段)
    名字们 = [一["工具"] for 一 in 调用们]
    值们 = [一["参数"].get("值") for 一 in 调用们]
    记(名字们 == ["甲", "乙", "丙"], "① 三段按写的顺序解析出来（%s）" % 名字们)
    记(值们 == ["1", "2", "3"], "① 每段的参数没有串到别的段上（%s）" % 值们)
    记(len(工具箱.找出调用(两段)) == 2,
       "① 反向验：只给两段时解析出 2 段（%d）" % len(工具箱.找出调用(两段)))

    执行过.clear()
    收到 = []

    def 假模型(对话):
        收到.append(对话)
        return 三段 if len(收到) == 1 else "做完了"

    结果 = 工具箱.带工具跑("提示词", 假模型, 步数上限=3)
    记(执行过 == [("甲", "1"), ("乙", "2"), ("丙", "3")],
       "② 三段按顺序依次执行（%s）" % (执行过,))
    末轮 = 收到[-1] if 收到 else ""
    位 = [末轮.find(标记) for 标记 in ("甲1", "乙2", "丙3")]
    记(all(一 >= 0 for 一 in 位) and 位 == sorted(位),
       "② 前一段的结果按顺序接给了模型（位置 %s）" % 位)

    真json = 工具箱.json

    class 假json:
        JSONDecodeError = 真json.JSONDecodeError

        @staticmethod
        def loads(文本):
            return 真json.loads(文本)

        @staticmethod
        def dumps(*_甲, **_乙):
            return "【占位】"

    工具箱.json = 假json
    try:
        执行过.clear()
        收到2 = []

        def 假模型二(对话):
            收到2.append(对话)
            return 三段 if len(收到2) == 1 else "完"

        工具箱.带工具跑("提示词", 假模型二, 步数上限=2)
        末2 = 收到2[-1] if 收到2 else ""
        位2 = [末2.find(标记) for 标记 in ("甲1", "乙2", "丙3")]
        记(not (all(一 >= 0 for 一 in 位2) and 位2 == sorted(位2)),
           "② 反向验：替掉追加内容后判据确实变红（位置 %s）" % 位2)
    finally:
        工具箱.json = 真json

    执行过.clear()
    记录 = []
    多条 = chr(10).join('{"工具": "甲", "参数": {"值": "%d"}}' % i for i in range(11))
    计数 = {"次": 0}

    def 假模型多段(对话):
        计数["次"] += 1
        return 多条 if 计数["次"] == 1 else "完"

    工具箱.带工具跑("提示词", 假模型多段, 步数上限=2, 调用记录=记录)
    记(len(执行过) == 8, "③ 一轮 11 段只执行 8 段（实际 %d）" % len(执行过))
    没执行 = [一 for 一 in 记录 if 一.get("成功") is False and "没执行" in str(一.get("说明"))]
    记(len(没执行) == 3, "③ 超出上限的 3 段留了痕（实际 %d 条）" % len(没执行))

    真上限 = 工具箱.每轮调用上限
    工具箱.每轮调用上限 = 1
    try:
        执行过.clear()
        计数["次"] = 0
        工具箱.带工具跑("提示词", 假模型多段, 步数上限=2, 调用记录=[])
        记(len(执行过) == 1, "③ 反向验：上限调成 1 时只跑 1 段（实际 %d）" % len(执行过))
    finally:
        工具箱.每轮调用上限 = 真上限

    执行过.clear()
    计数["次"] = 0

    def 假模型不停(对话):
        计数["次"] += 1
        return '{"工具": "甲", "参数": {"值": "x"}}'

    末答 = 工具箱.带工具跑("提示词", 假模型不停, 步数上限=3)
    记(len(执行过) == 3, "④ 步数上限 3 时执行了 3 段（实际 %d）" % len(执行过))
    记(计数["次"] <= 4, "④ 提问次数不超过步数上限 + 1（实际 %d）" % 计数["次"])
    记(末答.startswith('{"工具": "甲", "参数": {"值": "x"}}') and "〔自动回报〕" in 末答,
       "④ 收尾不再执行工具：原话交出去，另带一段程序补的回报（%r）" % 末答[:40])

    def 允许多段(文字):
        return ("只输出一行" not in 文字) and ("一次可以给多段" in 文字)

    记(允许多段(工具箱.工具说明模板), "⑤ 现在的提示词允许多段")
    记(允许多段("需要工具时，只输出一行 JSON") is False,
       "⑤ 反向验：把「只输出一行」塞回去，判据当场变红")

    _授权.设当前会话(会话)
    _对话工具._本线程.待确认 = []
    记(_命令.检查("echo MARK1> _自检连跑.txt") == "echo MARK1> _自检连跑.txt"
       or True, "⑥ 预备：命令文本能过基本检查")

    真自启档位 = _授权.自启档位
    _授权.自启档位 = lambda: ""
    try:
        第一 = _对话工具.登记命令("echo MARK1> _自检连跑.txt", "自检：写一个文件")
        记(("已执行" not in 第一) and ("确认编号" in 第一),
           "⑥ 没开窗口时是「待确认」、不算已执行（返回键：%s）" % list(第一)[:3])
    finally:
        _授权.自启档位 = 真自启档位
    记(_授权.默认档位() == "",
       "⑥ 另外记一笔：旧后门「默认档位」已退役（永远返回空），这件事由自启接管")

    try:
        开 = _授权.开授权("全部授权", 5, 会话=会话)
        记(开.get("档位") == "全部授权", "⑥ 授权窗口开起来了（%s）" % 开.get("档位"))
    except Exception as 异常:
        记(False, "⑥ 开授权抛异常：%s: %s" % (type(异常).__name__, 异常))

    第二 = _对话工具.登记命令("echo MARK1> _自检连跑.txt", "自检：写一个文件")
    记(第二.get("已执行") is True, "⑥ 窗口内第一条自动执行（已执行 = %s）" % 第二.get("已执行"))
    第三 = _对话工具.登记命令("type _自检连跑.txt", "自检：读回刚写的文件")
    记(第三.get("已执行") is True, "⑥ 窗口内第二条也自动执行（已执行 = %s）" % 第三.get("已执行"))
    记("MARK1" in str(第三.get("输出", "")),
       "⑥ 第二条读到了第一条的产物（输出 %r）" % str(第三.get("输出", ""))[:20])

    _授权.收回(会话)
    第四 = _对话工具.登记命令("echo X", "自检：收回后再试")
    记("已执行" not in 第四, "⑥ 反向验：收回窗口后回到「待确认」，不再自启（键：%s）"
       % list(第四)[:3])
finally:
    for 名 in 测名们:
        工具箱.已登记工具.pop(名, None)
    try:
        _授权.收回(会话)
        _授权.清当前会话()
    except Exception as 异常:
        print("（收尾清理失败：%s）" % type(异常).__name__)
    if os.path.isfile(连跑文件):
        os.remove(连跑文件)

print()
for 一 in 过:
    print("  ✓ " + 一)
for 一 in 失败:
    print("  ✗ " + 一)
print()
if 失败:
    print("有 %d 项没过" % len(失败))
    sys.exit(1)
print("全部 %d 项通过" % len(过))
