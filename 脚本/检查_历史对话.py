
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from 地基 import 大模型, 注册表, 配置, 提示词, 工具箱

注册表.全部加载(os.path.join(配置.根目录, "能力"))
import 能力.创造模式 as 创造模式

结果 = []


def 检查(名字, 通过):
    结果.append((名字, bool(通过)))


跑完了 = [False]
报过了 = [False]


def 报结论():
    if 报过了[0]:
        return 0
    报过了[0] = True
    坏的 = 0
    print()
    if not 跑完了[0]:
        print("⚠ 自检半路中断（看上面的报错），下面是**中断前已经跑完的部分**：")
    for 名字, 通过 in 结果:
        print(("  通过  " if 通过 else "  失败  ") + 名字)
        坏的 += 0 if 通过 else 1
    if 跑完了[0]:
        print("全部 %d 项通过" % len(结果) if not 坏的 else "%d 项失败" % 坏的)
    else:
        print("中断前跑了 %d 项：通过 %d、失败 %d" % (len(结果), len(结果) - 坏的, 坏的))
    return 坏的


import atexit
atexit.register(报结论)


超长 = "老师：内容\n助手：好的\n" * 5000

截断后, 是否截断 = 创造模式.截断历史(超长)
检查("① 超长历史被一次性压实（不是滑窗）",
    是否截断 and len(截断后) <= 创造模式.压实到 + 40 < 创造模式.历史上限)
检查("② 压实后带上了「已压实」标记", 截断后.startswith("（更早的对话已压实）"))

短历史 = "老师：你好\n助手：在"
原样, 是否截断2 = 创造模式.截断历史(短历史)
检查("③ 没超长的历史原样不动", 原样 == 短历史 and 是否截断2 is False)

看到 = {}


def 假模型(提示词原文):
    看到["提示词"] = 提示词原文
    return "好的"


大模型.问 = 假模型

创造模式.处理("我叫什么", "老师：我叫王老师")
检查("④ 历史真的进了提示词", "王老师" in 看到.get("提示词", ""))

输出 = 创造模式.处理("在吗", 超长)
检查("⑤ 超长历史下对话照样能进行", 输出.get("正文") == "好的")
检查("⑥ 提示里说明了已压实", "压实" in 输出.get("提示", ""))

try:
    创造模式.处理("啊" * (创造模式.内容长度上限 + 1))
    检查("⑦ 单条消息过长仍是明确报错", False)
except ValueError:
    检查("⑦ 单条消息过长仍是明确报错", True)

模板原文 = 提示词.读取("创造模式")
检查("⑧ 模板里留了 {工具说明} 的位置", "{工具说明}" in 模板原文)

实填 = 提示词.填充(模板原文, 工具说明=工具箱.工具说明文字(),
                 之前的对话="【历史占位】", 老师这次说的="【本次占位】")
位置工具 = 实填.find(工具箱.工具说明文字())
位置历史 = 实填.find("【历史占位】")
位置本次 = 实填.find("【本次占位】")
检查("⑨ 工具说明排在两个变量前面（进得了缓存前缀）",
    0 <= 位置工具 < 位置历史 < 位置本次)

固定段1 = 实填[:位置历史]
实填2 = 提示词.填充(模板原文, 工具说明=工具箱.工具说明文字(),
                  之前的对话="另一段完全不同的历史", 老师这次说的="另一句完全不同的话")
固定段2 = 实填2[:实填2.find("另一段完全不同的历史")]
检查("⑩ 换了输入，固定段仍然逐字节相同", 固定段1 == 固定段2)

跑完了[0] = True
sys.exit(0 if 报结论() == 0 else 1)
