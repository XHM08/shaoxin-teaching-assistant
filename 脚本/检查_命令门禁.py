
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from 地基 import 配置
from 能力 import _命令
import 能力.命令 as 命令能力

结果 = []


def 记(名字, 通过, 说明):
    结果.append((名字, bool(通过), 说明))


def 拦得住(文本):
    try:
        _命令.检查(文本)
        return False
    except ValueError:
        return True


def 报的什么(动作):
    try:
        值 = 动作()
        return False, "没被拒，拿到：" + str(值)[:44]
    except ValueError as 异常:
        return True, type(异常).__name__ + "：" + str(异常)[:48]


漏的 = [关键词 for 关键词, _原因 in _命令.禁用清单
        if not 拦得住(关键词 + " 随便什么参数")]
记("① 禁用清单每一条都被拦住", not 漏的,
  ("清单 %d 条，全部拦住" % len(_命令.禁用清单)) if not 漏的
  else "漏了：" + "、".join(漏的))

大写拦住 = 拦得住("  SHUTDOWN /S /T 0  ")
记("② 大写和前后空格绕不过去", 大写拦住,
  "「  SHUTDOWN /S /T 0  」被拦下" if 大写拦住 else "居然放行了")

提醒 = _命令.风险提示("pip install python-pptx")
放行 = not 拦得住("pip install python-pptx")
记("③ 危险词只提醒不拦（装依赖是老师的正当需求）",
  bool(提醒) and 放行 and "pip install" in 提醒,
  "提醒到「pip install」且放行" if (提醒 and 放行 and "pip install" in 提醒)
  else "提醒=" + repr(提醒[:30]) + " 放行=" + str(放行))

普通提醒 = _命令.风险提示("echo 你好")
记("④ 普通命令不给无谓提醒", 普通提醒 == "",
  "「echo 你好」没有危险提醒" if 普通提醒 == "" else "却提醒了：" + 普通提醒[:40])

超长拦 = 拦得住("x" * (_命令.命令长度上限 + 1))
记("⑤ 超长命令被拒", 超长拦,
  "上限 %d 字，超了被拦" % _命令.命令长度上限 if 超长拦 else "居然放行了")
空拦 = 拦得住("   ")
记("⑥ 空命令被拒", 空拦, "空白命令被拦" if 空拦 else "居然放行了")

原命令 = "echo 门禁自检用的普通命令"
号 = _命令.登记(原命令)

被拒, 说明 = 报的什么(lambda: _命令.取票(号, 原命令 + " 多了一句"))
记("⑦ 原文对不上 → 拒", 被拒 and "对不上" in 说明, 说明)

try:
    _命令.取票(号, 原命令)
    过 = True
    理由 = "票还在，正确原文通过"
except ValueError as 异常:
    过 = False
    理由 = "票被吃掉了：" + str(异常)[:34]
记("⑧ 原文对不上之后票还在，正确的那次仍能过", 过, 理由)

被拒, 说明 = 报的什么(lambda: _命令.取票(号, 原命令))
记("⑨ 同一张票用第二次 → 拒", 被拒, 说明)

被拒, 说明 = 报的什么(lambda: _命令.取票("999999", 原命令))
记("⑩ 没登记过的编号 → 拒", 被拒, 说明)

真运行 = _命令.运行
记录 = []


def 假运行(文本, 工作目录, 超时秒数):
    记录.append((文本, 工作目录, 超时秒数))
    return {"退出码": 0, "输出": "（自检用桩，没有真的执行）"}


def 假记一笔(*实参, **键参):
    审计记录.append((实参, 键参))


真记一笔 = 命令能力.审计.记一笔
审计记录 = []
命令能力.审计.记一笔 = 假记一笔
_命令.运行 = 假运行


def 拒了吗(动作):
    try:
        值 = 动作()
    except ValueError as 异常:
        return True, "抛 ValueError：" + str(异常)[:34]
    if isinstance(值, dict) and "已拒绝执行" in str(值.get("提示", "")):
        return True, "返回字典：" + str(值.get("提示"))[:26]
    return False, "既没被拒也没抛异常，拿到：" + str(值)[:34]


try:
    需要确认 = bool(配置.读取().get("命令", {}).get("需要确认", True))
    记("⑪ 配置里的「命令.需要确认」是开着的（关掉等于把门一拆了）", 需要确认,
      "需要确认 = True" if 需要确认 else "！！需要确认 = False，门一形同不存在")

    记录.clear()
    拒了, 说明 = 拒了吗(lambda: 命令能力.处理执行("echo 门禁自检", "", 确认="否"))
    记("⑫ 不传确认 → 拒绝，且没有真的跑", 拒了 and not 记录,
      说明 + "；运行调用 " + str(len(记录)) + " 次")

    记录.clear()
    拒了, 说明 = 拒了吗(lambda: 命令能力.处理执行("echo 门禁自检", "", 确认="是", 编号=""))
    记("⑬ 传了确认但没有编号 → 拒绝（当年被绕过的就是这条）",
      拒了 and "编号" in 说明 and not 记录,
      说明 + "；运行调用 " + str(len(记录)) + " 次")

    记录.clear()
    新号 = 命令能力.处理("echo 另一条命令")["编号"]
    拒了, 说明 = 拒了吗(
        lambda: 命令能力.处理执行("echo 另一条命令 改过一点", "", 确认="是", 编号=新号))
    记("⑭ 编号对、命令改过一个字 → 拒绝", 拒了 and not 记录,
      说明 + "；运行调用 " + str(len(记录)) + " 次")

    记录.clear()
    好号 = 命令能力.处理("echo 门禁自检该跑的那条")["编号"]
    答 = 命令能力.处理执行("echo 门禁自检该跑的那条", "", 确认="是", 编号=好号)
    到了 = len(记录) == 1 and 记录[0][0] == "echo 门禁自检该跑的那条"
    记("⑮ 确认 + 原封不动的编号 → 真的交给运行（用桩证明门是活的）", 到了,
      ("运行被调到，命令原文一致：" + 记录[0][0]) if 到了
      else "运行调用 " + str(len(记录)) + " 次，提示=" + str(答.get("提示"))[:30])

    记录.clear()
    拒了, 说明 = 拒了吗(
        lambda: 命令能力.处理执行("echo 门禁自检该跑的那条", "", 确认="是", 编号=好号))
    记("⑯ 同一张票在整条路上再用一次 → 拒绝", 拒了 and not 记录,
      说明 + "；运行调用 " + str(len(记录)) + " 次")
except Exception as 异常:
    记("自检半路出错", False, type(异常).__name__ + "：" + str(异常)[:60])
finally:
    _命令.运行 = 真运行
    命令能力.审计.记一笔 = 真记一笔

for 序 in range(_命令.待确认上限 + 20):
    _命令.登记("echo 占位 " + str(序))
现在 = len(_命令._待确认表)
记("⑰ 待确认表不超过上限", 现在 <= _命令.待确认上限,
  "上限 %d，现在 %d 条" % (_命令.待确认上限, 现在))

坏的 = 0
print()
for 名字, 通过, 说明 in 结果:
    print(("  通过  " if 通过 else "  失败  ") + 名字 + ("　→　" + 说明 if 说明 else ""))
    坏的 += 0 if 通过 else 1
print("全部 %d 项通过" % len(结果) if not 坏的 else "%d 项失败" % 坏的)
sys.exit(0 if not 坏的 else 1)
