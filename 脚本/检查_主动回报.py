
import io
import os
import sys
import tempfile

根 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, 根)

from 地基 import 工具箱

过, 失败 = [], []
名 = "自检造文件"

if 名 in 工具箱.已登记工具:
    print("跳过：测试工具名「%s」已被占用，本次没验" % 名)
    sys.exit(3)

临时目录 = tempfile.mkdtemp(prefix="邵新-主动回报-")
试文件 = os.path.join(临时目录, "产出.txt")


def 记(条件, 说明):
    (过 if 条件 else 失败).append(说明)


四段标记 = ("1. 做了什么", "2. 产出的文件", "3. 结果数字", "4. 要老师定的点")


def 跑(假模型, 步数上限=2):
    收到 = []

    def 包一层(对话):
        收到.append(对话)
        return 假模型(len(收到))

    return 工具箱.带工具跑("提示词", 包一层, 步数上限=步数上限), 收到


try:
    io.open(试文件, "w", encoding="utf-8").write("x")
    try:
        工具箱.登记工具(名, "自检用，零参数", [], lambda: {"文件": 试文件})
    except ValueError as 异常:
        记(False, "登记测试工具失败：%s" % 异常)

    调用们 = 工具箱.找出调用('{"工具": "%s"}' % 名)
    记(len(调用们) == 1 and 调用们[0]["参数"] == {},
       "① 省略「参数」的调用被认下来（%s）" % (调用们,))
    记(工具箱.找出调用('{"工具": "根本没有这个工具"}') == [],
       "① 没登记的名字仍然不认（不许把随便一句话当调用）")

    答短, _ = 跑(lambda 次: '{"工具": "%s"}' % 名 if 次 == 1 else "好了", 步数上限=2)
    记("〔自动回报〕" in 答短 and all(标记.split(". ")[1] in 答短 for 标记 in 四段标记),
       "② 动过工具但回答太短时，程序补出完整四段回报（%s）" % 答短.replace(chr(10), " / ")[:60])
    记("调用了" in 答短 and "1 次" in 答短, "② 补的回报里带着工具名与调用次数（取自本轮事实）")

    答聊, _ = 跑(lambda 次: "就聊聊，没动工具", 步数上限=2)
    记("〔自动回报〕" not in 答聊, "② 纯聊天不补回报（不硬凑格式）")

    四段答 = ("1. 做了什么：跑了一次" + chr(10) + "2. 产出的文件：" + 试文件
              + chr(10) + "3. 结果数字：1 次" + chr(10) + "4. 要老师定的点：无")
    答全, _ = 跑(lambda 次: '{"工具": "%s"}' % 名 if 次 == 1 else 四段答)
    记("〔自动回报〕" not in 答全, "② 模型自己按四段写了就不重复补")

    答, 收到 = 跑(lambda 次: '{"工具": "%s"}' % 名 if 次 == 1 else "做完了", 步数上限=2)
    记("〔自动回报〕" in 答, "② 早退路径：模型漏报时补了〔自动回报〕块")
    记(试文件 in 答, "② 补的内容里带着产出文件的绝对路径")
    末次 = 收到[-1] if 收到 else ""
    记(all(标记 in 末次 for 标记 in 四段标记),
       "④ 收尾那次问模型带着四段回报要求（缺：%s）"
       % [标记 for 标记 in 四段标记 if 标记 not in 末次])

    答2, _ = 跑(lambda 次: '{"工具": "%s"}' % 名 if 次 == 1 else "做完了，文件在 " + 试文件)
    记("〔自动回报〕" in 答2 and 试文件 in 答2,
       "③ 只报了文件、没按四段写：仍然补四段，且不丢原文（%s）"
       % 答2.replace(chr(10), " / ")[:50])

    答3, 收到3 = 跑(lambda 次: '{"工具": "%s"}' % 名 if 次 == 1 else '{"工具": "%s"}' % 名,
                    步数上限=2)
    记("〔自动回报〕" in 答3, "④ 步数耗尽路径：同样补了〔自动回报〕")
    记(all(标记 in (收到3[-1] if 收到3 else "") for 标记 in 四段标记),
       "④ 步数耗尽路径：收尾那次也带着四段回报要求")

    真解别名 = 工具箱.解别名
    工具箱.解别名 = lambda 名字: None
    try:
        假调用 = 工具箱.找出调用('{"工具": "%s"}' % 名)
    finally:
        工具箱.解别名 = 真解别名
    记(假调用 == [], "⑤ 反向验：解析不到名字时零参数调用确实被判空（%s）" % (假调用,))

    空对话 = ""
    记(not all(标记 in 空对话 for 标记 in 四段标记),
       "⑥ 反向验：对话里没有四段要求时，④ 的判据确实为假")
finally:
    工具箱.已登记工具.pop(名, None)
    for 路 in (试文件,):
        try:
            os.remove(路)
        except OSError as 异常:
            print("（清理临时文件失败：%s）" % type(异常).__name__)
    try:
        os.rmdir(临时目录)
    except OSError as 异常:
        print("（清理临时目录失败：%s）" % type(异常).__name__)

print()
for 一 in 过:
    print("  ✓ " + 一)
for 一 in 失败:
    print("  ✗ " + 一)
print()
if 失败:
    print("有 %d 项没过" % len(失败))
    sys.exit(1)
print("全部 %d 项通过" % len(过))
