
import csv
import importlib.util
import io
import os
import sys

根 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, 根)
输出目录 = os.environ.get("QUESTIONNAIRE_OUT", "")

归类表 = [
    ("外形·真人", ("青少年", "学姐", "老师", "教师", "大叔", "人形", "人的形象", "像人", "貌美",
                   "漂亮", "好看", "帅", "女生", "男生", "女孩", "短发", "大眼睛", "青年"), ("学生",)),
    ("外形·动物", ("小狗", "猪", "老鼠", "小动物", "动植物", "动物", "肥鱼"), ()),
    ("外形·卡通动漫", ("卡通", "动漫", "二次元", "奥特曼", "王者", "机器人", "小帮", "星星", "豆包"), ()),
    ("气质·可爱", ("可爱", "萌", "天真", "美丽", "青春活力"), ()),
    ("气质·亲和", ("亲和", "平易近人", "温和", "亲近", "善解人意", "像朋友", "热心"), ()),
    ("气质·有趣", ("有趣", "幽默", "风趣", "古灵精怪", "乐子", "热情"), ()),
    ("气质·聪明", ("聪明", "聪慧", "智慧", "有学识", "细致", "了解学生", "读懂"), ()),
    ("声音", ("声音",), ()),
    ("外观细节", ("蓝色", "裙子", "极简", "小装饰", "八中", "色调", "鲜艳", "多彩", "轻发", "布展"), ()),
    ("答的是功能不是形象", ("答疑", "解题", "讲题", "题目", "好用", "实用"), ()),
    ("不表态 / 不需要", (), ("无", "暂无", "不清楚", "不建议", "没有", "无。", "不了")),
]
未归类名 = "未归类"
看得很清 = "[不清]"


def 载入():
    规格 = importlib.util.spec_from_file_location(
        "问卷汇总_被读", os.path.join(根, "脚本", "问卷汇总_按题干.py"))
    模块 = importlib.util.module_from_spec(规格)
    规格.loader.exec_module(模块)
    模块.输出目录 = 输出目录
    return 模块


def 归类(句):
    命 = []
    for 名, 含词, 精确词 in 归类表:
        if any(词 in 句 for 词 in 含词) or 句 in 精确词:
            命.append(名)
    return 命


def 主():
    if not 输出目录:
        raise SystemExit("没设输出目录：先 export QUESTIONNAIRE_OUT=<问卷汇总目录>")
    模块 = 载入()
    好, 坏, 读不成 = 模块.读结果们(os.path.join(输出目录, "结果_题干"))

    按题 = {}
    跳过 = []
    for 记 in 好:
        for 一 in 记["题们"]:
            干 = 一["题干"]
            if "形象" not in 干:
                continue
            if 模块.是空(一["作答"], 干):
                continue
            键 = 模块.主键(干)
            袋 = 按题.setdefault(键, {"题": 干.replace(chr(10), " ").strip(), "答们": {}})
            值 = 模块.归一(模块.去掉姓名(一["作答"]))
            袋["答们"][值] = 袋["答们"].get(值, 0) + 1

    段们, 长表, 小结 = [], [], []
    for 序, 键 in enumerate(sorted(按题, key=lambda 键: -sum(按题[键]["答们"].values())), 1):
        袋 = 按题[键]
        总 = sum(袋["答们"].values())
        类计, 未归数 = {}, 0
        归法 = {}
        for 值, 数 in 袋["答们"].items():
            命 = 归类(值)
            归法[值] = 命
            if not 命:
                未归数 += 数
                长表.append([序, 袋["题"][:40], 值, 数, 未归类名])
                continue
            for 名 in 命:
                类计[名] = 类计.get(名, 0) + 数
            长表.append([序, 袋["题"][:40], 值, 数, "、".join(命)])

        段们 += ["## %d. %s" % (序, 袋["题"][:60]), "",
                 "作答 %d 份，不同写法 %d 种；其中 %d 份没归上类。"
                 % (总, len(袋["答们"]), 未归数), "",
                 "| 主题 | 份数 | 占作答（非互斥） |", "|---|---|---|"]
        for 名, 数 in sorted(类计.items(), key=lambda 对: -对[1]):
            段们.append("| %s | %d | %.0f%% |" % (名, 数, 100.0 * 数 / 总))
        段们.append("| %s | %d | %.0f%% |" % (未归类名, 未归数, 100.0 * 未归数 / 总))
        段们.append("")
        if 未归数:
            段们 += ["没归上的原文：" + "；".join(值 for 值 in 归法 if not 归法[值]), ""]
        段们 += ["原文（同写法已合并）：", ""]
        for 值, 数 in sorted(袋["答们"].items(), key=lambda 对: -对[1]):
            段们.append("- %s%s　→　%s" % (值, "" if 数 == 1 else "（%d 份）" % 数,
                                          "、".join(归法[值]) or 未归类名))
        段们.append("")
        小结.append((序, 袋["题"][:40], 总, 类计, 未归数))

    文 = ["# 形象题汇总", "", "XR: C", "",
          "- 日期：2026-11-03",
          "- 底数：读出 %d 张 / 读取失败 %d 张 / 结果文件坏了 %d 个；未填不计。"
          % (len(好), len(坏), len(读不成)),
          "- 范围：题干里含「形象」的两道开放题；两题各自成表，不合并。",
          "- 归类：一条答案命中多个词就记多个主题，所以各主题份数加起来大于作答数，占比不是互斥份额。",
          "- 词表在 `脚本/形象建议汇总.py` 顶部；`[不清]` 是没看清，不算「不表态」。",
          "- 合计：两题作答共 %d 份（同一学生被问两次，未去重）。"
          % sum(sum(袋["答们"].values()) for 袋 in 按题.values()), ""]
    for 序, 题, 总, 类计, 未归数 in 小结:
        前 = sorted(类计.items(), key=lambda 对: -对[1])[:4]
        if 前:
            文.append("- 第 %d 题（作答 %d 份）最多的四类：%s"
                      % (序, 总, "、".join("%s %d 份" % (名, 数) for 名, 数 in 前)))
        else:
            文.append("- 第 %d 题（作答 %d 份）：没有归上类的答案，全在「未归类」里" % (序, 总))
    文.append("")
    文 += 段们

    with io.open(os.path.join(输出目录, "形象建议.md"), "w", encoding="utf-8") as 文件:
        文件.write(chr(10).join(文) + chr(10))
    try:
        写表 = io.open(os.path.join(输出目录, "形象建议.csv"), "w",
                      encoding="utf-8-sig", newline="")
    except PermissionError:
        raise SystemExit("形象建议.csv 打不开（大概是正在 Excel 里开着），关掉再跑一遍")
    with 写表 as 文件:
        写 = csv.writer(文件)
        写.writerow(["题序", "题目", "原文", "份数", "归类"])
        写.writerows(长表)

    总份 = sum(sum(袋["答们"].values()) for 袋 in 按题.values())
    print("形象题 %d 道，作答 %d 份（两题合计，含同一学生被问两次），归类行 %d 条"
          % (len(按题), 总份, len(长表)))
    print("汇总：" + os.path.join(输出目录, "形象建议.md"))


if __name__ == "__main__":
    主()
