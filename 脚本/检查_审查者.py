
import os
import shutil
import sys
import tempfile

根 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, 根)

from 地基 import 大模型, 配置, 提示词, 记忆库
from 能力 import _审查, 创造模式, _对话工具

失败 = []
条数 = 0


def 记(名, 通过, 说明=""):
    global 条数
    条数 += 1
    print(("  ✓ " if 通过 else "  ✗ ") + 名 + ("" if 通过 else "　→　" + str(说明)))
    if not 通过:
        失败.append(名)


def 假问(回答们, 记录=None):
    队列 = list(回答们)

    def 问(提示词原文, **参数):
        if 记录 is not None:
            记录.append(str(提示词原文)[:40])
        return 队列.pop(0) if 队列 else "APPROVE"
    return 问


def 打桩(假问函数, 假跑一轮):
    大模型.问 = 假问函数
    _对话工具.带工具跑一轮 = 假跑一轮
    坏 = []
    if 创造模式.大模型.问 is not 假问函数:
        坏.append("创造模式.大模型.问")
    if _审查.大模型.问 is not 假问函数:
        坏.append("_审查.大模型.问")
    if 创造模式._对话工具.带工具跑一轮 is not 假跑一轮:
        坏.append("创造模式._对话工具.带工具跑一轮")
    return (not 坏), 坏


def 主():
    原问, 原跑 = 大模型.问, _对话工具.带工具跑一轮
    原取目录, 原读取 = 配置.取目录, 配置.读取
    临时 = tempfile.mkdtemp(prefix="审查者-")
    try:

        真提示词 = 原取目录("提示词")
        配置.取目录 = lambda 名: 临时 if 名 in ("教师数据", "日志") else 真提示词 if 名 == "提示词" else 原取目录(名)
        接管好 = (记忆库.目录() == os.path.join(临时, "记忆")
                and 配置.取目录("日志") == 临时
                and 配置.取目录("提示词") == 原取目录("提示词"))
        if not 接管好:
            print("目录接管没生效：拒绝往下跑（否则会写真实记忆/日志）")
            return 1
        记("① 记忆与日志接管到临时目录，提示词目录仍指真实位置", 接管好)

        记("② 提示词里有 APPROVE 与 REJECT 两种出口，五个占位符齐全",
           all(x in 提示词.读取("审查") for x in ("APPROVE", "REJECT", "{老师这次说的}",
                                             "{助手的回答}", "{调用记录}")))
        记("③ 提示词明确只审邵新的输出，不审老师",
           "不是老师" in 提示词.读取("审查"), "找不到「只审输出」这句话")


        记("④ APPROVE → 通过", _审查.解析("APPROVE")[0] == "通过")
        判, 问题们, _ = _审查.解析("REJECT:\n1. [高] 说保存了但其实没写｜第三段\n2. 漏了第二项｜开头")
        记("⑤ REJECT 逐条：级别、说明、位置对（缺级别按中）",
           判 == "有问题" and len(问题们) == 2 and 问题们[0]["级别"] == "高"
           and 问题们[0]["位置"] == "第三段" and 问题们[1]["级别"] == "中", 问题们)
        记("⑥ REJECT 但读不出条目 → 没跑成", _审查.解析("REJECT:\n没有编号")[0] == "没跑成")
        记("⑦ 没有结论 → 没跑成", _审查.解析("还行吧")[0] == "没跑成")
        记("⑧ 同时出现两种结论 → 没跑成", _审查.解析("APPROVE\nREJECT:")[0] == "没跑成")
        记("⑨ 空回复 → 没跑成", _审查.解析("")[0] == "没跑成")


        配置.读取 = lambda: {"审查": True}
        记("⑩ 动过手就审（哪怕回答很短）", _审查.要审吗("好", [{"工具": "写文件"}]))
        记("⑪ 纯闲聊不审", not _审查.要审吗("好", []))
        记("⑫ 长回答要审", _审查.要审吗("字" * 500, []))
        配置.读取 = lambda: {"审查": {"开启": False}}
        记("⑬ 关掉之后不审", not _审查.要审吗("字" * 500, [{"工具": "写文件"}]))


        排 = _审查.附到回答("原答", {"问题们": [{"级别": "低", "说明": "小的", "位置": ""},
                                            {"级别": "高", "说明": "大的", "位置": "第二段"}]})
        记("⑭ 附意见时高级别在前", 排.index("大的") < 排.index("小的") and "〔审查者〕" in 排)


        留, 丢 = _审查.过滤怪老师([
            {"级别": "中", "说明": "老师的要求不清楚", "位置": ""},
            {"级别": "中", "说明": "助手说已保存但记录里没有", "位置": ""}])
        记("⑭a 说老师的意见被丢掉、说邵新的留下",
           len(留) == 1 and "助手" in 留[0]["说明"] and len(丢) == 1, (留, 丢))
        记("⑭b 只提到老师的提问方式也算怪老师（不只是「要求」二字）",
           bool(_审查.过滤怪老师([{"级别": "低", "说明": "老师的问法太笼统", "位置": ""}])[1]))
        留2, 丢2 = _审查.过滤怪老师([{"级别": "中", "说明": "老师要求的三点只做了两点", "位置": ""}])
        记("⑭c 反向验：邵新漏做、句子里提到「老师要求」，必须保留",
           len(留2) == 1 and not 丢2, (留2, 丢2))


        def 跑一轮(提示, 问, 记录):
            记录.append({"工具": "写文件", "结果": "已写入"})
            return "回答甲", []

        调用记录 = []
        假 = 假问(['{"类别": "偏好", "内容": "五年级用北师大版"}',
                  "REJECT:\n1. [高] 说已保存但记录里没有写文件｜全篇"], 记录=调用记录)
        好, 坏处 = 打桩(假, 跑一轮)
        if not 好:
            print("打桩没生效：%s，拒绝往下跑（否则会真花钱）" % "、".join(坏处))
            return 1
        配置.读取 = lambda: {"审查": True, "记忆": True}
        结果 = 创造模式.处理("把这节课存下来")
        记("⑮ 抽取与审查都跑了：记忆落库 1 条、正文附了 1 处问题",
           结果["记忆"]["记了"] == 1 and 结果["审查"]["问题数"] == 1
           and "〔审查者〕" in 结果["正文"] and len(记忆库.取记忆(5)) == 1,
           (结果["记忆"], 结果["审查"]))
        记("⑯ 只报告不改答案：正文里原答案「回答甲」仍在",
           "回答甲" in 结果["正文"], 结果["正文"][:60])
        记("⑰ 调用顺序是「先抽取、后审查」（从提示词开头认出来）",
           len(调用记录) == 2 and "记住" in 调用记录[0] and "审查" in 调用记录[1], 调用记录)
        记("⑱ 提示里同时出现「记住」与「审查者」",
           "记住 1 条" in 结果["提示"] and "审查者：1 处问题" in 结果["提示"], 结果["提示"])


        审计路 = os.path.join(临时, "审计.jsonl")
        行们 = [__import__("json").loads(x) for x in open(审计路, encoding="utf-8").read().splitlines() if x.strip()]
        最后 = (行们[-1] if 行们 else {}).get("元信息") or {}
        记("⑳a 审计的 元信息 里有 审查/审查问题数/记住条数/小结合并 四个字段且值对得上",
           最后.get("审查") == "有问题" and 最后.get("审查问题数") == 1
           and 最后.get("记住条数") == 1 and 最后.get("小结合并") == 0,
           {k: 最后.get(k) for k in ("审查", "审查问题数", "记住条数", "小结合并")})


        调用记录 = []
        大模型.问 = 假问(['{"类别": "偏好", "内容": "课件放材料目录"}', "APPROVE"], 记录=调用记录)
        结果 = 创造模式.处理("把这节课存下来")
        记("⑲ 审查通过：正文不含〔审查者〕，判「通过」",
           "〔审查者〕" not in 结果["正文"] and 结果["审查"]["判"] == "通过", 结果["审查"])
        记("⑳ 这一轮正好两次调用（抽取 + 审查）", len(调用记录) == 2, len(调用记录))


        状态 = {"次": 0}

        def 先好后炸(提示词原文, **参数):
            状态["次"] += 1
            if 状态["次"] == 1:
                return ""
            raise RuntimeError("审查服务没响应")

        大模型.问 = 先好后炸
        结果 = 创造模式.处理("把这节课存下来")
        记("㉑ 审查失败：正文一字不差仍是原答案，判「没跑成」且说明带异常名",
           结果["正文"].strip() == "回答甲" and 结果["审查"]["判"] == "没跑成"
           and "RuntimeError" in (结果["审查"].get("说明") or ""), 结果["审查"])
        记("㉒ 没跑成时不往正文塞假意见", "〔审查者〕" not in 结果["正文"])


        调用记录 = []
        大模型.问 = 假问(["APPROVE"], 记录=调用记录)
        _对话工具.带工具跑一轮 = lambda 提示, 问, 记录: ("好的", [])
        结果 = 创造模式.处理("谢谢")
        记("㉓ 纯闲聊（没动手、回答短）：抽取与审查都不跑，零调用",
           len(调用记录) == 0 and 结果["审查"]["判"] == "跳过" and 结果["记忆"]["记了"] == 0,
           len(调用记录))


        调用记录 = []
        大模型.问 = 假问(["APPROVE"], 记录=调用记录)
        _对话工具.带工具跑一轮 = 跑一轮
        配置.读取 = lambda: {"审查": {"开启": False}, "记忆": {"开启": False}}
        结果 = 创造模式.处理("把这节课存下来")
        记("㉔ 两个开关都关：正文原样、零调用",
           len(调用记录) == 0 and 结果["审查"]["判"] == "跳过" and 结果["记忆"]["记了"] == 0
           and 结果["正文"].strip() == "回答甲", (len(调用记录), 结果["审查"], 结果["记忆"]))
    except Exception as 错:
        记("检查本身跑完了", False, "%s: %s" % (type(错).__name__, 错))
    finally:
        大模型.问, _对话工具.带工具跑一轮 = 原问, 原跑
        配置.取目录, 配置.读取 = 原取目录, 原读取
        shutil.rmtree(临时, ignore_errors=True)

    print()
    print("全部 %d 项通过" % 条数 if not 失败 else "通过 %d / 共 %d" % (条数 - len(失败), 条数))
    return 0 if not 失败 else 1


if __name__ == "__main__":
    sys.exit(主())
