
import io
import json
import os
import sys

根 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, 根)

from 地基 import 配置
from 能力 import _授权

过, 失败 = [], []


def 记(条件, 说明):
    (过 if 条件 else 失败).append(说明)


配置路 = 配置.配置文件
原配置 = io.open(配置路, encoding="utf-8").read() if os.path.isfile(配置路) else "{}"
会话 = "自检-自启"
普通 = "echo AUTO1"
危险 = "pip install requests"
禁用 = "format c:"


def 设定(档位):
    对象 = json.loads(原配置)
    段 = 对象.get("命令") if isinstance(对象.get("命令"), dict) else {}
    段["自启"] = 档位
    段.pop("默认档位", None)
    对象["命令"] = 段
    io.open(配置路, "w", encoding="utf-8").write(json.dumps(对象, ensure_ascii=False, indent=2))


def 干净会话():
    _授权._表.pop(会话, None)


try:
    设定("")
    干净会话()
    果 = _授权.跑一条(会话, 普通, 配置.根目录, 30)
    记(果.get("动作") != "自动", "① 自启关着时不自动跑（动作 %s）" % 果.get("动作"))
    记(_授权.查授权(会话)["档位"] == "", "① 关着时也没有顺手开出一个窗口")

    设定("全部授权")
    干净会话()
    果 = _授权.跑一条(会话, 普通, 配置.根目录, 30)
    记(果.get("动作") == "自动", "② 自启开会后普通命令自动跑（动作 %s）" % 果.get("动作"))
    状态 = _授权.查授权(会话)
    记(状态["档位"] == "全部授权", "③ 自动撑起来的窗口档位是「全部授权」（%s）" % 状态["档位"])
    记(bool(状态.get("不限时")), "③ 自动开的窗口是不限时的（不限时=%s）" % 状态.get("不限时"))

    果 = _授权.跑一条(会话, 危险, 配置.根目录, 30)
    记(果.get("动作") == "自动", "④ 窗口内危险命令也直接跑（动作 %s）" % 果.get("动作"))

    果 = _授权.跑一条(会话, 禁用, 配置.根目录, 30)
    记(果.get("动作") == "自动" and 果.get("放行禁用清单") is True,
       "⑤ 窗口内禁用清单命令放行、并标了「放行禁用清单」（动作 %s / 标记 %s）"
       % (果.get("动作"), 果.get("放行禁用清单")))

    _授权.收回(会话)
    果 = _授权.跑一条(会话, 普通, 配置.根目录, 30)
    记(果.get("动作") != "自动", "⑥ 收回之后不再自动开窗（动作 %s）" % 果.get("动作"))
    记(_授权.查授权(会话)["结束原因"] == "窗口已收回",
       "⑥ 收回留下的原因是「窗口已收回」（%s）" % _授权.查授权(会话)["结束原因"])

    干净会话()
    _授权.开授权("全部授权", "不限", 会话=会话)
    for _ in range(_授权.档位表["全部授权"]):
        _授权.跑一条(会话, "echo x", 配置.根目录, 30)
    记(_授权.查授权(会话)["结束原因"] == "窗口已用完",
       "⑦ 条数跑满后窗口结束（%s）" % _授权.查授权(会话)["结束原因"])
    果 = _授权.跑一条(会话, 普通, 配置.根目录, 30)
    记(果.get("动作") != "自动", "⑦ 条数用完后不再自动续窗（动作 %s）" % 果.get("动作"))

    try:
        _授权.设自启("超级授权")
        记(False, "⑧ 设自启时写「超级授权」应该被拒，结果设成了")
    except ValueError:
        记(True, "⑧ 设自启时不认识的档位被拒")
    记(_授权.自启档位() in ("", "全部授权"),
       "⑧ 拒绝之后自启没被写坏（现在=%r）" % _授权.自启档位())

    设定("全部授权")
    干净会话()
    真自启档位 = _授权.自启档位
    _授权.自启档位 = lambda: ""
    try:
        果 = _授权.跑一条(会话, 普通, 配置.根目录, 30)
        记(果.get("动作") != "自动",
           "⑨ 反向验：自启档位为空时同一条命令回到待确认（动作 %s）" % 果.get("动作"))
        记(_授权.查授权(会话)["档位"] == "", "⑨ 反向验：这时也没有窗口被自动撑起来")
    finally:
        _授权.自启档位 = 真自启档位
finally:
    io.open(配置路, "w", encoding="utf-8").write(原配置)
    try:
        _授权.收回(会话)
        _授权._表.pop(会话, None)
    except Exception as 异常:
        print("（收尾清理失败：%s）" % type(异常).__name__)

print()
for 一 in 过:
    print("  ✓ " + 一)
for 一 in 失败:
    print("  ✗ " + 一)
print()
if 失败:
    print("有 %d 项没过" % len(失败))
    sys.exit(1)
print("全部 %d 项通过" % len(过))
