
import json
import os
import shutil
import sys
import tempfile

根 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, 根)

from 地基 import 大模型, 记忆库, 配置
from 能力 import _记忆

失败 = []
条数 = 0


def 记(名, 通过, 说明=""):
    global 条数
    条数 += 1
    print(("  ✓ " if 通过 else "  ✗ ") + 名 + ("" if 通过 else "　→　" + str(说明)))
    if not 通过:
        失败.append(名)


def 假问(回答们):
    队列 = list(回答们)

    def 问(提示词原文, **参数):
        return 队列.pop(0) if 队列 else ""
    return 问


def 主():
    原取目录, 原问 = 配置.取目录, 大模型.问
    临时 = tempfile.mkdtemp(prefix="记忆-")


    临时记忆 = os.path.join(临时, "记忆")
    try:


        _原取目录 = 配置.取目录
        配置.取目录 = lambda 名: 临时 if 名 in ("教师数据", "日志") else _原取目录(名)
        if 记忆库.目录() != 临时记忆:
            print("接管没生效：拒绝往下跑（否则会写进真实记忆库）")
            return 1
        记("① 记忆目录接管生效（不碰真实 教师数据/记忆）", 记忆库.目录() == 临时记忆)
        记("② 目录不存在时自动建", os.path.isdir(临时记忆))


        记忆库.记一条("五年级三班用北师大版", "偏好")
        记忆库.记一条("课件放 材料/五年级/", "约定")
        记忆库.记一条("   ", "偏好")
        取 = 记忆库.取记忆(10)
        记("③ 空内容不记（空白那条被丢掉）", len(取) == 2 and 取[0]["内容"] == "课件放 材料/五年级/", 取)
        记("④ 取记忆是最新的在前", 取[0]["时间"] >= 取[1]["时间"])

        记忆库.关键记忆上限 = 3
        for 序 in range(5):
            记忆库.记一条("第%d条" % 序)
        记("⑤ 超上限丢最旧的（上限 3 → 留最近 3 条）",
           [x["内容"] for x in 记忆库.取记忆(10)][:3] == ["第4条", "第3条", "第2条"],
           [x["内容"] for x in 记忆库.取记忆(10)])
        记忆库.关键记忆上限 = 200


        路 = os.path.join(临时记忆, "关键记忆.jsonl")
        with open(路, "a", encoding="utf-8") as 文件:
            文件.write('{"类别": "偏好", "内容": "半截\n')
        记("⑥ 半截行被跳过，其余照样读得出来", len(记忆库.取记忆(10)) == 3, len(记忆库.取记忆(10)))

        记("⑦ 记忆文本按行拼，空库给空串",
           记忆库.记忆文本(5).count("\n") <= 4 and 记忆库.记忆文本(0) == "")


        记忆库.存摘要("甲", 9000, "前面聊了五年级的分数的除法，定下用 demo-real 风格")
        记忆库.存摘要("乙", 9000, "另一段会话的摘要")
        记("⑧ 摘要按会话分开取",
           len(记忆库.取摘要("甲")) == 1 and len(记忆库.取摘要("乙")) == 1
           and "分数的除法" in 记忆库.摘要文本("甲"), 记忆库.摘要文本("乙"))
        记("⑨ 注入文本包含长期记忆与会话摘要",
           "【长期记忆】" in _记忆.注入文本("甲") and "【更早对话的小结】" in _记忆.注入文本("甲"),
           _记忆.注入文本("甲")[:60])


        原抽取 = _记忆.抽取开着吗
        try:
            _记忆.抽取开着吗 = lambda: True
            大模型.问 = 假问(['{"类别": "偏好", "内容": "五年级三班用北师大版"}\n'
                            '{"类别": "约定", "内容": "课件文件名用课题名"}\n'
                            '不是 JSON 的一行'])
            第一批 = _记忆.抽取("老师说的", "回答")
            记("⑩ 抽取落库，坏行被跳过（记 2 条）", len(第一批["记了"]) == 2, 第一批)
            第二批 = _记忆.抽取("老师说的", "回答")
            记("⑪ 同一句不重复记（两句都已在库里，这次一条都不加）",
               len(第二批["记了"]) == 0, 第二批["记了"])
            大模型.问 = 假问(["{\"类别\": \"偏好\", \"内容\": \"新的一条事实\"}"])
            第三批 = _记忆.抽取("老师说的", "回答")
            记("⑪b 新的事实照常记进去（去重不是把库锁死）",
               len(第三批["记了"]) == 1 and 第三批["记了"][0]["内容"] == "新的一条事实", 第三批["记了"])
            _记忆.抽取开着吗 = lambda: False
            记("⑫ 关掉之后不调用模型也不落库", _记忆.抽取("a", "b")["记了"] == [])
        finally:
            _记忆.抽取开着吗 = 原抽取


        原压缩 = _记忆.压缩开着吗
        try:
            _记忆.压缩开着吗 = lambda: True
            大模型.问 = 假问(["这是那段对话的摘要，讲清了要求和结论，字数够用"])
            历史 = "甲" * 9000 + "\n最近的一段"
            新, 压了, 说明 = _记忆.压缩(历史, "甲", 压到=1000)
            记("⑬ 压缩成功：历史变短，含小结与最近的尾巴",
               压了 and len(新) < len(历史) and "【这一段的小结】" in 新 and 新.endswith("最近的一段"), 说明)
            记("⑭ 压缩结果进了摘要库", any("讲清了要求" in x["摘要"] for x in 记忆库.取摘要("甲")))

            def 炸(提示词原文, **参数):
                raise RuntimeError("模型超时")
            大模型.问 = 炸
            新2, 压了2, 说明2 = _记忆.压缩(历史, "甲", 压到=1000)
            记("⑮ 压缩失败：原历史原样返回，不吞内容",
               (not 压了2) and 新2 == 历史 and "RuntimeError" in 说明2, 说明2)
            大模型.问 = 假问(["太短"])
            新3, 压了3, _ = _记忆.压缩(历史, "甲", 压到=1000)
            记("⑯ 摘要太短也不采用（宁可退回原样）", (not 压了3) and 新3 == 历史)
            记("⑰ 历史本来就不长时不调用模型",
                _记忆.压缩("短", "甲", 压到=1000)[1] is False)
        finally:
            _记忆.压缩开着吗 = 原压缩


        原压缩开 = _记忆.压缩开着吗
        try:
            _记忆.压缩开着吗 = lambda: True
            调用 = []
            大模型.问 = 假问(["合并后的一段小结，把要求和结论都保留了"], 记录=调用) if False else (lambda 提示, **参数: (调用.append(1), "合并后的一段小结，把要求和结论都保留了")[1])
            记忆库.清摘要("甲")
            for 号 in range(5):
                记忆库.存摘要("甲", 100, "第%d段小结" % 号)
            少于 = _记忆.慢压("甲", 阈值=6)
            记("⑳ 没到阈值不合并、不调用模型", 少于["合并"] == 0 and not 调用, 少于)
            记忆库.存摘要("甲", 100, "第5段小结")
            到了 = _记忆.慢压("甲", 阈值=6)
            剩 = 记忆库.取摘要("甲", 9)
            记("㉑ 到阈值就合并成一条，旧的全部收掉",
               到了["合并"] == 6 and len(剩) == 1 and "合并后的一段小结" in 剩[0]["摘要"], (到了, len(剩)))
            记("㉒ 合并时真的调了一次模型", len(调用) == 1, len(调用))
            def 炸2(提示, **参数):
                raise RuntimeError("合并超时")
            大模型.问 = 炸2
            记忆库.清摘要("乙")
            for 号 in range(7):
                记忆库.存摘要("乙", 100, "乙第%d段" % 号)
            没合上 = _记忆.慢压("乙", 阈值=6)
            记("㉓ 合并失败：一条都不删，说明里带异常名",
               没合上["合并"] == 0 and len(记忆库.取摘要("乙", 99)) == 7 and "RuntimeError" in 没合上["说明"], 没合上)
        finally:
            _记忆.压缩开着吗 = 原压缩开


        记忆库.清空("关键")
        记("⑱ 清空关键记忆只清关键，摘要还在",
          记忆库.取记忆(10) == [] and len(记忆库.取摘要("甲")) >= 1)
        记忆库.清空("全部")
        记("⑲ 清空全部", 记忆库.取记忆(10) == [] and 记忆库.取摘要("甲") == [])
    except Exception as 错:
        记("检查本身跑完了", False, "%s: %s" % (type(错).__name__, 错))
    finally:
        配置.取目录, 大模型.问 = 原取目录, 原问
        shutil.rmtree(临时, ignore_errors=True)

    print()
    print("全部 %d 项通过" % 条数 if not 失败 else "通过 %d / 共 %d" % (条数 - len(失败), 条数))
    return 0 if not 失败 else 1


if __name__ == "__main__":
    sys.exit(主())
