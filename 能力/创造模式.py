
import inspect
import time

from 地基 import 审查记录, 大模型, 审计, 提示词, 配置, 注册表, 工具箱

from 能力 import _对话工具, _授权, _记忆, _审查

class _回答过滤:

    def __init__(self, 下游):
        self.下游 = 下游
        self.缓冲 = ""
        self.是回答 = None

    def __call__(self, 类型, 文本):
        if 类型 != "回答":
            self.下游(类型, 文本)
            return
        if self.是回答 is False:
            return
        if self.是回答 is True:
            self.下游("回答", 文本)
            return

        self.缓冲 += 文本
        开头 = self.缓冲.lstrip()
        if not 开头.startswith("{") and len(self.缓冲) >= 2:
            self.是回答 = True
            self.下游("回答", self.缓冲)
            self.缓冲 = ""
            return
        if not 开头.startswith("{"):
            return
        if len(self.缓冲) < 12:
            return
        是调用 = ('"工具"' in self.缓冲) or ('"tool"' in self.缓冲.lower())
        self.是回答 = not 是调用
        if self.是回答:
            self.下游("回答", self.缓冲)
        self.缓冲 = ""


内容长度上限 = 2000
历史上限 = 20000
压实到 = 8000

参数表 = [
    {"代号": "内容", "标签": "想做什么", "类型": "textarea", "必填": True,
     "示例": "例如：用 demo-real 的风格，出一节「分数的除法」的课件"},
    {"代号": "之前的对话", "标签": "之前的对话", "类型": "textarea", "必填": False},
]


def 截断历史(文本):
    if len(文本) <= 历史上限:
        return 文本, False
    尾巴 = 文本[-压实到:]
    切点 = 尾巴.find("\n")
    if 切点 >= 0:
        尾巴 = 尾巴[切点 + 1:]
    return "（更早的对话已压实）\n" + 尾巴, True


def 处理(内容, 之前的对话="", 片段回调=None):
    开始时刻 = time.time()
    内容 = str(内容).strip()
    if not 内容:
        raise ValueError("请输入内容。")
    if len(内容) > 内容长度上限:
        raise ValueError("这次说的太长了（最多 " + str(内容长度上限) + " 字）。")

    历史 = str(之前的对话).strip() or "（这是第一句）"
    历史, 是否压缩, 压缩说明 = _记忆.压缩(历史, "创造模式", 压到=压实到)
    if 是否压缩:
        是否截断 = True
    else:
        历史, 是否截断 = 截断历史(历史)
    记忆块 = _记忆.注入文本("创造模式")
    if 记忆块:
        历史 = 历史 + "\n\n" + 记忆块

    调用记录 = []
    try:
        提示词原文 = 提示词.填充(提示词.读取("创造模式"),
                           工具说明=工具箱.工具说明文字(),
                           之前的对话=历史, 老师这次说的=内容)
        大模型.清空思考()
        服务商 = str((配置.读取().get("创造模式") or {}).get("服务商") or "").strip()

        def 问模型(提示):
            函数 = 大模型.问
            try:
                形参 = inspect.signature(函数).parameters
            except (TypeError, ValueError):
                形参 = {}
            要流式 = bool(片段回调) and "流式问" in dir(大模型) and 函数 is 大模型.问
            if 要流式:
                过滤 = _回答过滤(片段回调)
                参数 = {"收到": 过滤}
                if "服务商" in inspect.signature(大模型.流式问).parameters and 服务商:
                    参数["服务商"] = 服务商
                return 大模型.流式问(提示, **参数)
            if not 服务商:
                return 函数(提示)
            if "服务商" in 形参:
                return 函数(提示, 服务商=服务商)
            return 函数(提示)

        回答, 待确认命令 = _对话工具.带工具跑一轮(提示词原文, 问模型, 调用记录)
    except Exception as 异常:
        审计.记一笔("创造模式", {"内容字数": len(内容), "工具调用次数": len(调用记录)},
                    成功=False, 秒数=time.time() - 开始时刻, 备注=type(异常).__name__)
        raise

    记忆结果 = {"记了": [], "说明": "", "合并": 0}
    if 调用记录 or len(回答) >= 400:
        记忆结果 = _记忆.抽取(内容, 回答, "创造模式")
        合并结果 = _记忆.慢压("创造模式")
        记忆结果["合并"] = 合并结果.get("合并", 0)

    审查结果 = _审查.审查(回答, 内容, 调用记录)
    审查记录.记一条(审查结果.get("判", "没跑成"),
                 审查结果.get("问题们") or [],
                 老师说的=内容, 回答字数=len(回答 or ""),
                 用了几件工具=len(调用记录 or []))

    审计.记一笔("创造模式",
                {"工具调用次数": len(调用记录), "待确认命令数": len(待确认命令),
                 "历史字数": len(历史), "内容字数": len(内容),
                 "审查": 审查结果.get("判"), "审查问题数": len(审查结果.get("问题们") or []),
                 "记住条数": len(记忆结果.get("记了") or []), "小结合并": 记忆结果.get("合并", 0)},
                成功=True, 秒数=time.time() - 开始时刻)

    提示 = "调用了工具：" + ("、".join(一条["工具"] for 一条 in 调用记录) if 调用记录 else "无")
    if 是否压缩:
        提示 += "　（更早的对话已压缩成摘要）"
    elif 是否截断:
        提示 += "　（更早的对话太长，已压实）"
    if 记忆结果.get("记了"):
        提示 += "　｜记住 %d 条" % len(记忆结果["记了"])
    if 记忆结果.get("合并"):
        提示 += "　｜旧小结合并 %d 条" % 记忆结果["合并"]
    if 审查结果.get("判") == "有问题":
        提示 += "　｜审查者：%d 处问题（详情在「审查者」页）" % len(审查结果["问题们"])
    elif 审查结果.get("判") == "通过":
        提示 += "　｜审查者：通过"
    elif 审查结果.get("判") == "跳过":
        提示 += "　｜审查者：这轮没审（回答较短，省一轮）"
    else:
        提示 += "　｜审查没跑成"
    return {
        "提示": 提示,
        "正文": 回答,
        "思考": 大模型.取思考(),
        "思考块": 大模型.思考块们(),
        "条目": [],
        "调用记录": 调用记录,
        "待确认命令": 待确认命令,
        "记忆": {"记了": len(记忆结果.get("记了") or []), "说明": 记忆结果.get("说明", "")},
        "审查": {"判": 审查结果.get("判"), "问题数": len(审查结果.get("问题们") or []),
               "说明": 审查结果.get("说明", "")},
        "授权": _授权.查授权(_授权.当前会话()),
    }


注册表.登记(
    代号="创造模式",
    标题="创造模式",
    说明="和 AI 对话，让它直接出课件、备课、查材料、查环境、跑命令（命令需人工确认）",
    参数=参数表,
    处理函数=处理,
)
