
import time

from 地基 import 审计, 大模型, 提示词, 注册表
from 地基 import 技能包 as 技能包库

from 能力 import _档案


def 处理(编号, 技能包, 问题):
    开始时刻 = time.time()
    _档案.要求已签()

    编号 = _档案.校验编号(编号)
    if not _档案.已注册(编号):
        raise ValueError("这个编号还没注册：" + 编号 + "，先去「学生注册」登记一下。")
    if not str(问题).strip():
        raise ValueError("问题不能为空。")

    技能包库.校验代号(技能包)
    提示词原文 = 提示词.填充(提示词.读取("答疑"),
                        教师档案=技能包库.读技能包全文(技能包), 问题=问题)

    姓名们 = _档案.姓名字样(编号)
    问题文本 = str(问题)
    撞上的 = [值 for 值 in 姓名们 if 值 in 问题文本]
    撞上的 += [值 for 值 in 姓名们
               if len(值) >= 2 and 值 in 提示词原文 and 值 not in 撞上的]
    if 撞上的:
        raise ValueError(
            "拒绝发送：这次要发出去的内容里出现了学生的姓名（"
            + "、".join(撞上的) + "）。\n"
            "《学生数据处理约定》二规定姓名对照表不出本机，4.2 的发送范围只有三项。\n"
            "如果是你自己在问题里写了名字，去掉名字再问一次就行。"
        )
    try:
        回答 = 大模型.问(提示词原文)
    except Exception as 异常:
        审计.记一笔("学生问答", {"编号": 编号}, 成功=False,
                    秒数=time.time() - 开始时刻, 备注=type(异常).__name__)
        raise

    _档案.记一条(编号, {"类别": "问答", "技能包": 技能包,
                       "问题": str(问题).strip()})
    审计.记一笔("学生问答", {"编号": 编号, "提问字数": len(问题)}, 成功=True,
                秒数=time.time() - 开始时刻)

    return {
        "提示": "已作答。这次问答计入了 " + 编号 + " 的档案。",
        "正文": 回答,
        "条目": [],
    }


注册表.登记(
    代号="学生问答",
    标题="学生问答",
    说明="学生用自己的编号提问，回答按这位老师的讲法，问答计入该生档案",
    参数=[
        {"代号": "编号", "标签": "你的编号（如 S01）", "类型": "text", "必填": True},
        {"代号": "技能包", "标签": "请哪位老师来答", "类型": "text", "必填": True,
         "可选项来源": "技能包"},
        {"代号": "问题", "标签": "你的问题", "类型": "textarea", "必填": True,
         "示例": "例如：老师，为什么除以分数要倒过来乘？"},
    ],
    处理函数=处理,
)
