
import time

from 地基 import 审计, 课件, 课件图, 大模型, 注册表, 提示词
from 地基 import 技能包 as 技能包模块

from 能力 import 讲稿配音

讲稿上限 = 400
提示词名 = "已有课件讲稿"

参数表 = [
    {"代号": "课件文件", "标签": "要用的课件（先放进 课件输出/）", "类型": "text", "必填": True,
     "可选项来源": "课件"},
    {"代号": "技能包", "标签": "按哪位教师的讲法写讲稿", "类型": "text", "必填": True,
     "可选项来源": "技能包"},
    {"代号": "要不要配音", "标签": "要不要配音（默认要；填“不”则跳过）", "类型": "text",
     "必填": False},
]


def _一页素材(一页):
    标题 = str(一页.get("标题") or "").strip()
    文字 = str(一页.get("文字") or "").strip()
    return 标题, 文字


def 组装(技能包正文, 一页, 上一页讲稿):
    标题, 文字 = _一页素材(一页)
    return 提示词.填充(
        提示词.读取(提示词名),
        技能包=技能包正文,
        页码=str(一页.get("页") or "?"),
        标题=(标题 or "（这一页没有标题）"),
        页面文字=(文字 or "（这一页只有图，没有文字）"),
        上一页=(上一页讲稿[-120:] if 上一页讲稿 else "（这是第一页）"))


def _洗讲稿(原文):
    文字 = str(原文 or "").strip()
    for 头 in ("讲稿：", "讲稿:", "这一页讲稿：", "这一页讲稿:"):
        if 文字.startswith(头):
            文字 = 文字[len(头):].strip()
    if len(文字) >= 2 and 文字[0] == 文字[-1] and 文字[0] in ("“", "「", '"', "'"):
        文字 = 文字[1:-1].strip()
    if len(文字) > 讲稿上限:
        文字 = 文字[:讲稿上限]
    return 文字


def 处理(课件文件, 技能包="", 要不要配音="要"):
    开始时刻 = time.time()
    路径 = 讲稿配音.取课件路径(课件文件)
    if not str(技能包).strip():
        raise ValueError("请选一位教师的技能包：讲稿要按他的讲法写")
    正文 = 技能包模块.读技能包全文(技能包)

    页们 = 课件.读各页(路径)
    if not 页们:
        raise ValueError("这份课件里一页都没有？换一份试试：" + 课件文件)
    缺讲稿 = [一页 for 一页 in 页们 if not str(一页.get("备注") or "").strip()]
    已有 = len(页们) - len(缺讲稿)

    警告 = []
    写好 = 0
    if 缺讲稿:
        课件.备份成(路径, "补讲稿前")
        新讲稿 = {}
        上一页讲稿 = ""
        for 一页 in 页们:
            现有 = str(一页.get("备注") or "").strip()
            if 现有:
                上一页讲稿 = 现有
                continue
            try:
                这回 = _洗讲稿(大模型.问(组装(正文, 一页, 上一页讲稿)))
            except Exception as 异常:
                警告.append("第 %s 页的讲稿没写成（%s）。那页上课时没有声音"
                          % (一页.get("页"), type(异常).__name__))
                continue
            if not 这回:
                警告.append("第 %s 页模型给了空讲稿，跳过了" % 一页.get("页"))
                continue
            新讲稿[int(一页["页"])] = 这回
            上一页讲稿 = 这回
        if 新讲稿:
            写好 = 课件.写备注(路径, 新讲稿)

    配音目录, 音频表, 配音说明 = "", {}, ""
    if 讲稿配音.要配音吗(要不要配音):
        能, 原因 = 讲稿配音.能配音吗()
        if not 能:
            配音说明 = "没配音（" + 原因 + "）"
        else:
            配音起 = time.time()
            try:
                配音目录, 配音条目 = 讲稿配音.合成整份(路径, 讲稿配音.取配置语速(), 警告)
                音频表 = {条["页"]: 条["音频"] for 条 in 配音条目}
                配音说明 = "配音用了 %.0f 秒" % (time.time() - 配音起)
            except Exception as 异常:
                配音说明 = "配音没成（" + str(异常).splitlines()[0][:60] + "）"

    页图表 = {}
    try:
        位置 = 课件图.导出各页(路径, 警告)
        页图表 = {序号: 课件图.页图地址(位置["目录名"], 序号)
                 for 序号 in range(1, 位置["页数"] + 1)}
    except Exception as 异常:
        警告.append("每页图没导出来（" + type(异常).__name__ + "：" + str(异常).splitlines()[0][:60]
                  + "）：上课时这一页只能用文字显示")

    条目 = []
    for 序号, 一页 in enumerate(课件.读各页(路径), 1):
        条目.append({
            "页": 序号,
            "标题": str(一页.get("标题", "")),
            "要点": 课件.要点成行(一页.get("要点")),
            "讲稿": str(一页.get("备注", "")),
            "音频": 音频表.get(序号, ""),
            "页图": 页图表.get(序号, ""),
        })

    没讲稿的页 = [一["页"] for 一 in 条目 if not 一["讲稿"]]
    提示 = "用你这份课件（共 %d 页）：" % len(条目)
    if 缺讲稿:
        提示 += "补了 %d 页讲稿" % 写好
        if 已有:
            提示 += "，另外 %d 页本来就有讲稿（一个字没动）" % 已有
    else:
        提示 += "每页都已经有讲稿了，直接上课"
    if 没讲稿的页:
        提示 += "；第 %s 页还没有讲稿" % "、".join(str(x) for x in 没讲稿的页)
    if 配音说明:
        提示 += "；" + 配音说明
    for 一句 in 警告[:2]:
        提示 += "；" + 一句

    该补 = len(缺讲稿)
    成功 = (该补 == 0 or 写好 == 该补) and (not 缺讲稿 or 写好 > 0) and bool(条目)         and (not 页图表 or all(x.get("页图") for x in 条目))
    审计.记一笔("用已有课件", {"课件": str(课件文件), "页数": len(条目), "补了讲稿": 写好,
                          "该补": 该补, "警告条数": len(警告)},
                成功=成功, 秒数=time.time() - 开始时刻)
    return {"提示": 提示, "正文": "", "条目": 条目,
            "课件文件": str(课件文件), "课名": 课件文件, "配音目录": 配音目录}


注册表.登记(
    代号="用已有课件",
    标题="用已有课件上课",
    说明="拿一份老师自己已有的 .pptx：只给没有讲稿的页补讲稿（可选配音、导出每页图），然后一页页讲",
    参数=参数表,
    处理函数=处理,
)
