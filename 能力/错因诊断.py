
import time

from 地基 import 审计, 大模型, 提示词, 注册表
from 地基 import 技能包 as 技能包库


def 错误类型清单():
    参数们 = 注册表.取能力("录入学生记录")["参数"]
    for 参数项 in 参数们:
        if 参数项["代号"] == "错误类型":
            return list(参数项.get("可选项") or [])
    raise ValueError("「录入学生记录」里没有「错误类型」这个参数，诊断结果没法归类。")


def 取一行(回答, 标签):
    for 行 in str(回答).splitlines():
        行 = 行.strip()
        if 行.startswith(标签):
            return 行[len(标签):].strip().lstrip("：:").strip()
    return ""


def 处理(技能包, 学科, 题目, 作答):
    开始时刻 = time.time()
    技能包库.校验代号(技能包)
    for 名, 值 in (("学科", 学科), ("题目", 题目), ("学生作答", 作答)):
        if not str(值).strip():
            raise ValueError(名 + "不能为空。")

    清单 = 错误类型清单()
    提示词原文 = 提示词.填充(
        提示词.读取("错因诊断"),
        错误类型清单=" / ".join(清单),
        教师档案=技能包库.读技能包全文(技能包),
        题目=str(题目).strip(),
        作答=str(作答).strip(),
    )

    try:
        回答 = 大模型.问(提示词原文)
    except Exception as 异常:
        审计.记一笔("错因诊断", {"学科": 学科}, 成功=False,
                    秒数=time.time() - 开始时刻, 备注=type(异常).__name__)
        raise

    判定 = 取一行(回答, "错误类型")
    在清单里 = 判定 in 清单
    审计.记一笔("错因诊断", {"学科": 学科, "类型在清单里": 在清单里}, 成功=True,
                秒数=time.time() - 开始时刻)

    条目 = [
        {"字段": "错误类型",
         "内容": 判定 or "（模型没给出）",
         "备注": "" if 在清单里 else "不在清单里，录入档案时请手动改"},
        {"字段": "为什么会错", "内容": 取一行(回答, "为什么会错"), "备注": ""},
        {"字段": "怎么讲", "内容": 取一行(回答, "怎么讲"), "备注": ""},
    ]
    return {
        "提示": ("" if 在清单里 else
                "注意：模型给的类型「" + (判定 or "空") + "」不在错误类型清单里，"
                "录入前请手动改成清单里的一个。\n")
               + "诊断完成。**这次内容没有落盘** —— 它不属于采集清单三项，"
                 "要留档请去「学生档案馆」录一条作答记录（错误类型会自动填好）。",
        "正文": 回答,
        "条目": 条目,
        "错误类型": 判定 if 在清单里 else "",
    }


注册表.登记(
    代号="错因诊断",
    标题="错因诊断",
    说明="按某位教师的方法，判断这道题为什么错、并给出他的讲法（不落盘）",
    参数=[
        {"代号": "技能包", "标签": "用哪位教师的方法", "类型": "text", "必填": True,
         "可选项来源": "技能包"},
        {"代号": "学科", "标签": "学科", "类型": "text", "必填": True,
         "示例": "例如：数学"},
        {"代号": "题目", "标签": "题目", "类型": "textarea", "必填": True},
        {"代号": "作答", "标签": "学生的作答", "类型": "textarea", "必填": True},
    ],
    处理函数=处理,
)
