
import time

from 地基 import 审计, 配置, 大模型, 材料, 提示词, 注册表, 技能包

维度清单 = [
    "核心自述",
    "教师名言",
    "课堂教学方案方法",
    "对待学生态度",
    "学生评价",
    "课堂教学风格",
    "对当下教育的看法",
    "送给学生的一句话",
    "教育方针",
    "教师基本信息（年龄、职称、工作年限、性别、教学科目）",
    "自我评价（保留原话，不要润色）",
    "当下目标",
    "课堂风格",
    "高频错因",
    "纠错策略",
]

参数表 = [
    {"代号": "文件", "标签": "选择材料", "类型": "text", "必填": True,
     "可选项来源": "材料"},
    {"代号": "代号", "标签": "技能包代号（小写字母、数字、连字符）",
     "类型": "text", "必填": True, "示例": "例如：math-fraction-teacher-a"},
    {"代号": "描述", "标签": "技能包描述（决定「什么时候该用它」）",
     "类型": "text", "必填": True,
     "示例": "例如：小学数学分数除法，用乡村场景打比方，先举例后下定义"},
]


def 组装提示词(材料原文, 维度=None):
    维度 = 维度 or 维度清单
    编号后 = "\n".join(str(序号) + ". " + 一项 for 序号, 一项 in enumerate(维度, 1))
    return 提示词.填充(提示词.读取("蒸馏"), 维度=编号后, 材料原文=材料原文)


def 从文字蒸馏(材料原文, 技能包代号, 描述, 假模式=False, 服务商=None):
    回答 = 大模型.问(组装提示词(材料原文), 服务商=服务商, 假模式=假模式)
    _, 正文 = 技能包.拆头尾(回答)
    原文 = 技能包.组装技能包(技能包代号, 描述, 正文)
    路径 = 技能包.保存技能包(配置.取目录("技能包"), 技能包代号, 原文)
    return 原文, 路径


def 处理(文件, 代号, 描述):
    开始时刻 = time.time()
    材料原文 = 材料.读材料(材料.材料路径(文件))
    try:
        原文, 路径 = 从文字蒸馏(材料原文, 代号, 描述)
    except Exception as 异常:
        审计.记一笔("蒸馏", {"材料字数": len(材料原文)}, 成功=False,
                    秒数=time.time() - 开始时刻, 备注=type(异常).__name__)
        raise
    审计.记一笔("蒸馏", {"材料字数": len(材料原文)}, 成功=True,
                秒数=time.time() - 开始时刻)
    return {
        "提示": "已生成：" + 路径,
        "正文": 原文,
        "条目": [],
    }


注册表.登记(
    代号="蒸馏",
    标题="经验蒸馏",
    说明="把一份教师材料蒸馏成结构化技能包（调用大模型）",
    参数=参数表,
    处理函数=处理,
)
