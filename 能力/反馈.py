每文件上限 = 6000
总量上限 = 20000
禁区 = ("密钥", "学生数据", "教师数据")


def 读代码(相对路径们):
    根 = os.path.normcase(os.path.abspath(配置.根目录))
    片段 = []
    读过的 = []
    总数 = 0
    for 一个 in 相对路径们:
        名 = str(一个 or "").strip().replace("\\", "/")
        if not 名:
            continue
        if os.path.isabs(名) or 名.startswith("/") or ":" in 名:
            raise ValueError("只认项目目录下的相对路径，不认绝对路径：" + 名)
        if any(段 == ".." for 段 in 名.split("/")):
            raise ValueError("路径里不许出现 ..（不许跳出项目目录）：" + 名)
        全 = os.path.normcase(os.path.abspath(os.path.join(根, 名)))
        if os.path.commonpath([根, 全]) != 根:
            raise ValueError("这个路径跑到项目目录外面去了：" + 名)
        顶层 = 名.split("/")[0]
        if 顶层 in 禁区:
            raise ValueError("「" + 顶层 + "/」里的东西不许发给外部模型：" + 名)
        if not os.path.isfile(全):
            raise ValueError("没找到这个文件：" + 名)
        with open(全, "r", encoding="utf-8", errors="replace") as 文件:
            正文 = 文件.read(每文件上限)
        正文 = 正文.replace("```", "'''")
        if len(正文) >= 每文件上限:
            正文 += "\n…（这个文件太长，只取了前 " + str(每文件上限) + " 字）"
        if 总数 + len(正文) > 总量上限:
            正文 = 正文[:max(0, 总量上限 - 总数)] + "\n…（总量到顶了）"
        片段.append("### " + 名 + "\n" + 正文)
        读过的.append(名)
        总数 += len(正文)
        if 总数 >= 总量上限:
            break
    return 片段, 读过的


def 拆文件名单(文本):
    return [一 for 一 in
            str(文本 or "").replace("，", ",").replace("、", ",").split(",")
            if 一.strip()]


def 取编号(反馈编号):
    原文 = str(反馈编号).strip()
    if not 原文.isdigit():
        raise ValueError("反馈编号要写数字（就是清单里那个号）。拿到的是："
                         + (原文 or "（空）"))
    return int(原文)


def 处理记反馈(类型, 内容, 影响面=""):
    号 = _反馈.记反馈(类型, 内容, 影响面)
    审计.记一笔("记反馈", {"反馈编号": 号, "类型": 类型}, 成功=True)
    return {
        "提示": "收到，这是第 " + str(号) + " 条反馈。"
                "（反馈是教师侧材料，存在 教师数据/ 里。"
                "学生自己提的意见请由老师转述 —— 学生那边不落盘。）",
        "正文": "",
        "条目": [],
        "反馈编号": 号,
    }


def 处理清单(只看="全部", 类型="全部"):
    范围 = str(只看 or "全部").strip()
    if 范围 not in ("全部", "未处理", "已处理"):
        raise ValueError("「只看」只能是：全部 / 未处理 / 已处理。拿到的是：" + 范围)
    种类 = str(类型 or "全部").strip()
    if 种类 != "全部" and 种类 not in _反馈.反馈类型:
        raise ValueError("「类型」只能是：全部 / " + " / ".join(_反馈.反馈类型))
    条 = _反馈.清单()
    if 范围 != "全部":
        条 = [一 for 一 in 条 if 一["状态"] == 范围]
    if 种类 != "全部":
        条 = [一 for 一 in 条 if 一["类型"] == 种类]
    已处理 = [一 for 一 in 条 if 一["状态"] == "已处理"]
    用时们 = [一["处理用时小时"] for 一 in 已处理
            if isinstance(一.get("处理用时小时"), float)]
    提要 = "共 " + str(len(条)) + " 条（" + 范围 + "／" + 种类 + "）"
    if 已处理:
        提要 += "，其中已处理 " + str(len(已处理)) + " 条"
        if 用时们:
            提要 += "，平均用了 " + str(round(sum(用时们) / len(用时们), 1)) + " 小时"
    提要 += "。这份清单里没有任何学生信息。"
    条目 = [{
        "反馈编号": 一["反馈编号"],
        "状态": 一["状态"],
        "类型": 一["类型"],
        "内容": 一["内容"],
        "影响面": 一["影响面"],
        "结果": 一["结果"],
        "提交号": 一["提交号"],
        "处理说明": 一["处理说明"],
        "时间": 一["时间"],
        "处理用时小时": 一["处理用时小时"],
    } for 一 in 条]
    return {"提示": 提要, "正文": "", "条目": 条目}


def 处理诊断(反馈编号, 相关文件=""):
    开始时刻 = time.time()
    号 = 取编号(反馈编号)
    一条 = _反馈.取一条(号)
    if 一条 is None:
        raise ValueError("没有编号 " + str(号) + " 这条反馈。先看一眼清单里有哪些号。")
    名单 = 拆文件名单(相关文件)
    片段, 读过的 = 读代码(名单)

    提示词原文 = 提示词.填充(
        提示词.读取("反馈诊断"),
        项目背景=项目背景,
        反馈内容=("【类型】" + 一条.get("类型", "") + "\n"
                + "【老师写的】" + 一条.get("内容", "") + "\n"
                + ("【影响面】" + 一条.get("影响面", "") if 一条.get("影响面") else "")),
        代码片段=("\n\n".join(片段) if 片段
                else "（老师这次没有指定要看的文件，所以下面没有任何代码。"
                     "那就只判断「下一步该看哪个文件」并说明理由，不要猜实现。）"),
    )
    try:
        草稿 = 大模型.问(提示词原文)
    except Exception as 异常:
        审计.记一笔("反馈诊断", {"反馈编号": 号}, 成功=False,
                    秒数=time.time() - 开始时刻, 备注=type(异常).__name__)
        raise
    审计.记一笔("反馈诊断", {"反馈编号": 号, "看了几个文件": len(读过的),
                          "文件们": 读过的[:6]}, 成功=True,
                秒数=time.time() - 开始时刻)
    return {
        "提示": "这是**草稿**，不是改动：没有写任何文件、没有执行任何命令。\n"
                "要落地的话，由人决定改不改；改完必须过自检 + 双向回归，再 git 提交。",
        "条目": [
            {"字段": "这条反馈", "内容": 一条.get("内容", ""), "备注": 一条.get("类型", "")},
            {"字段": "看了这些文件", "内容": "、".join(读过的) or "（没指定）", "备注": ""},
        ],
        "正文": 草稿,
        "反馈编号": 号,
    }


def 处理记反馈处理(反馈编号, 结果, 提交号="", 说明=""):
    号 = 取编号(反馈编号)
    _反馈.记处理(号, 结果, 提交号, 说明)
    审计.记一笔("记反馈处理", {"反馈编号": 号, "结果": 结果,
                            "提交号": str(提交号 or "").strip()}, 成功=True)
    return {
        "提示": "第 " + str(号) + " 条记为「" + 结果 + "」。"
                + ("提交号 " + str(提交号).strip() + " 也记下了 ——"
                   "「反馈 → 提交」这条链就接上了。" if str(提交号 or "").strip()
                   else "（没填提交号，这条链还差最后一环。）"),
        "正文": "",
        "条目": [],
    }


