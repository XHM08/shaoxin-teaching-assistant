
from 地基 import 记忆库, 审计, 注册表


def 处理(动作="查看", 确认=""):
    尝试 = {"动作": str(动作)}
    动作 = str(动作 or "查看").strip()
    if 动作 not in ("查看", "清空", "删除"):
        raise ValueError("动作有三个：查看 / 删除 / 清空")

    if 动作 == "查看":
        关键 = 记忆库.取记忆(20)
        摘要 = 记忆库.取摘要("创造模式", 3)
        结果 = {
            "关键条数": len(记忆库.取记忆(10 ** 6)),
            "摘要条数": len(记忆库.取摘要("创造模式", 10 ** 6)),
            "关键记忆": [{"内容": 一条["内容"], "类别": 一条.get("类别", ""),
                      "时间": 一条.get("时间", "")} for 一条 in 关键],
            "最近小结": [一条["摘要"] for 一条 in 摘要],
        }
        审计.记一笔("记忆库", 尝试, 成功=True, 秒数=0.0)
        return 结果

    if 动作 == "删除":
        内容 = str(确认 or "").strip()
        if not 内容:
            raise ValueError("要删哪一条？请在「确认」里填那条记忆的原文")
        删了 = 记忆库.删一条(内容)
        审计.记一笔("记忆库", {"动作": "删除"}, 成功=bool(删了), 秒数=0.0)
        return {"已删": 删了, "说明": "删掉了 %d 条" % 删了 if 删了 else "没找到这条（可能已被删）"}

    if str(确认).strip() != "确认清空":
        raise ValueError("清空记忆不可恢复。确实要清，请在「确认」里写：确认清空")
    删了 = 记忆库.清空("全部")
    审计.记一笔("记忆库", 尝试, 成功=True, 秒数=0.0, 备注="清空")
    return {"已清空": True, "说明": "关键记忆与对话小结都清掉了；档案与课件不受影响"}


注册表.登记(
    代号="记忆库",
    标题="本地记忆",
    说明="查看记住了哪些长期事实与会话小结；清空会删掉全部记忆（要写确认清空）。"
         "记忆只存在这台电脑上，清空不影响学生档案与课件。",
    参数=[
        {"代号": "动作", "标签": "查看 或 清空（默认查看）", "类型": "text", "必填": False,
         "示例": "查看"},
        {"代号": "确认", "标签": "删除时填原文；清空时填 确认清空", "类型": "text", "必填": False,
         "示例": "确认清空"},
    ],
    处理函数=处理,
)
