
import os
import time

from 地基 import 课件, 审计, 课件改, 配置, 注册表
from 能力 import 讲稿配音

参数表 = [
    {"代号": "课件文件", "标签": "改哪份课件", "类型": "text", "必填": True,
     "示例": "例如：张老师-分数的除法.pptx"},
    {"代号": "要改什么", "标签": "用一句话说要改什么", "类型": "text", "必填": True,
     "示例": "例如：第 3 页的讲稿太书面了，改成我平时说话的样子"},
    {"代号": "确认", "标签": "填「好」才真改（先看清单）", "类型": "text", "必填": False},
]

_上次清单 = {}
_上次清单上限 = 8


确认的说法 = ("好", "是", "行", "对", "可以", "确认", "ok", "OK")


def 要动手吗(值):
    return str(值 or "").strip() in 确认的说法


def 处理(课件文件, 要改什么, 确认=""):
    开始时刻 = time.time()
    路径 = 讲稿配音.取课件路径(课件文件)
    意见 = str(要改什么 or "").strip()
    if not 意见:
        raise ValueError("请用一句话说要改什么（例如：第 3 页的讲稿太书面了，改成我平时说话的样子）")

    印 = 课件.指纹(路径)
    键 = (str(路径), str(意见).strip(), str((印 or {}).get("内容") or ""))
    复用 = 要动手吗(确认) and 键 in _上次清单
    if 复用:
        清单 = _上次清单[键]
    else:
        清单 = 课件改.出清单(路径, 意见)
        _上次清单[键] = 清单
        while len(_上次清单) > _上次清单上限:
            _上次清单.pop(next(iter(_上次清单)))

    if not 要动手吗(确认):
        预览 = 课件改.预览清单(清单)
        审计.记一笔("改课件", {"课件": os.path.basename(路径), "阶段": "出清单",
                          "要改页数": len(课件改.要改的页(清单))},
                    成功=True, 秒数=time.time() - 开始时刻)
        提示 = ("这是拟好的改动清单 —— 看清楚没问题，就**再点一次**，"
              "把「确认」填成「好」，我才会真改（改之前会先备份一份）")
        if not 清单["改动"]:
            提示 = "这一句我没读出要改哪里 —— 换个说法再试（例如：第 3 页的讲稿改成我的口气）"
        return {"提示": 提示, "正文": 预览, "条目": [], "清单": 清单}

    警告 = []
    好页, 没成 = 课件改.执行清单(路径, 清单, 警告)

    配音说明 = ""
    if 好页:
        能, 原因 = 讲稿配音.能配音吗()
        if not 能:
            配音说明 = "；配音没跟着更新（" + 原因 + "）—— 要更新就先把语音服务起来，再点一次「讲稿配音」"
        else:
            try:
                讲稿配音.合成整份(路径, 1.0, 警告)
                配音说明 = "；改过那几页的配音也换成新的了"
            except Exception as 异常:
                配音说明 = ("；配音没更新（" + type(异常).__name__ + "：" +
                        str(异常).splitlines()[0][:50] + "）")

    提示 = "改好了：第 %s 页" % "、".join(str(x) for x in 好页) if 好页 else "没能改任何地方"
    if 没成:
        提示 += "；有 %d 处没改成：" % len(没成) + "；".join(没成[:2])
    for 一句 in 警告[:2]:
        提示 += "；" + 一句
    提示 += 配音说明

    审计.记一笔("改课件", {"课件": os.path.basename(路径), "阶段": "执行",
                       "改了页数": len(好页), "没成数": len(没成)},
                成功=bool(好页), 秒数=time.time() - 开始时刻)
    return {"提示": 提示, "正文": 课件改.预览清单(清单), "条目": [], "清单": 清单}


注册表.登记(
    代号="改课件",
    标题="改课件（用一句话改）",
    说明="老师用一句话说要改什么：先出改动清单给他看，确认后再改那份 pptx（改前自动备份）",
    参数=参数表,
    处理函数=处理,
)
