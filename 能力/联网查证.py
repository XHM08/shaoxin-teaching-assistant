
import time

from 地基 import 审计, 联网, 注册表

正文上限 = 60000


def 统一条数(原值):
    try:
        数 = int(str(原值).strip() or 5)
    except (TypeError, ValueError):
        raise ValueError("要几条结果？填个 1~%d 的数字" % 联网.最多条数) from None
    if 数 < 1:
        raise ValueError("条数至少是 1")
    return min(联网.最多条数, 数)


def 处理(问题, 网址="", 条数=5):
    开始时刻 = time.time()
    尝试 = {"提问字数": 0, "有网址": bool((网址 or "").strip())}
    try:
        问题 = (问题 or "").strip()
        网址 = (网址 or "").strip()
        尝试["提问字数"] = len(问题)
        if not 问题 and not 网址:
            raise ValueError("要么写个问题让我搜，要么给一个网址让我抓。")

        附言 = ""
        if 网址:
            条数 = 1
            原始 = 联网.抓取(网址)
            标题 = 原始.get("title") or 网址
            全文 = (原始.get("content") or "").strip()
            截断 = len(全文) > 正文上限
            正文 = 全文[:正文上限]
            if 截断:
                正文 += "\n\n（原文 %d 字，这里只放到 %d 字；要看后面的段落，把具体小节名告诉我。）" \
                        % (len(全文), 正文上限)
            条目 = [{"标题": 标题, "网址": 网址, "时间": "", "权威": "未知", "摘要": 正文[:160]}]
            提示 = "抓到「%s」，%d 字%s。" % (标题, len(全文), "（已截断）" if 截断 else "")
            if 问题:
                附言 = "这次只抓了你给的网页，没有拿「%s」去搜。" % 问题[:30]
        else:
            条数 = 统一条数(条数)
            原始 = 联网.搜索(问题, 条数=条数)
            if not isinstance(原始.get("results"), list):
                raise RuntimeError("接口返回的结构看不懂：" + str(原始)[:200])
            条目 = 联网.整理结果(原始, 上限=条数)
            for 一 in 条目:
                if 一.get("权威") is None:
                    一["权威"] = "未知"
            正文 = "\n\n".join(
                "%d. %s\n%s\n%s" % (序, 一["标题"], 一["摘要"] or "（无摘要）", 一["网址"])
                for 序, 一 in enumerate(条目, 1))
            if not 正文:
                正文 = "接口回了 200，但 results 是空的 —— 可能是真没搜到，也可能是查询太窄。换个说法再试一次。"
            提示 = "搜到 %d 条（用时 %.1f 秒）。" % (len(条目), time.time() - 开始时刻)
    except Exception as 异常:
        审计.记一笔("联网查证", 尝试, 成功=False, 秒数=time.time() - 开始时刻,
                    备注=type(异常).__name__)
        raise

    尝试["条数"] = len(条目)
    审计.记一笔("联网查证", 尝试, 成功=True, 秒数=time.time() - 开始时刻)
    提示 = 提示 + "内容是从网上抓的，用之前请自己核一眼来源。"
    if 附言:
        提示 = 提示 + " " + 附言
    return {"提示": 提示, "正文": 正文, "条目": 条目}


注册表.登记(
    代号="联网查证",
    标题="联网查证",
    说明="到网上查一件事：给问题就搜（带来源、时间、权威度），给网址就抓那一页正文",
    参数=[
        {"代号": "问题", "标签": "要查什么", "类型": "textarea", "必填": False,
         "示例": "例如：2026 年初中数学新课标有什么变化"},
        {"代号": "网址", "标签": "或者直接给一个网址（给了就只抓这一页）",
         "类型": "text", "必填": False, "示例": "https://api-docs.deepseek.com/"},
        {"代号": "条数", "标签": "要几条结果（1~10）", "类型": "number", "必填": False, "示例": "5"},
    ],
    处理函数=处理,
)
