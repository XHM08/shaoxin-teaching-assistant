
from 地基 import 注册表, 材料

默认最多 = 4000


def 处理(文件="", 最多字数=默认最多):
    文件 = str(文件 or "").strip()
    if not 文件:
        raise ValueError("要给我一个材料文件名（先看材料台账里有哪些）")
    try:
        上限 = int(最多字数)
    except (TypeError, ValueError):
        raise ValueError("「最多字数」要写整数")
    if 上限 < 100:
        raise ValueError("「最多字数」太小了，至少 100，现在 %d" % 上限)

    路 = 材料.材料路径(文件)
    原文 = 材料.读材料(路)
    if not 原文 or not 原文.strip():
        正文 = ("这份材料没读出文字。如果它是图片或扫描件，本来就没字可读，"
                "改用「看图片」让它看着讲。文件名：%s" % 文件)
        return {"正文": 正文, "字数": 0, "截断": False, "文件": 文件}

    总 = len(原文)
    截断 = 总 > 上限
    给 = 原文[:上限]
    尾巴 = ("（只给了前 %d 字，原文 %d 字；要把后面的也读出来，把「最多字数」调大）"
            % (上限, 总)) if 截断 else ""
    return {"正文": 给 + (chr(10) + 尾巴 if 尾巴 else ""), "字数": 总,
            "截断": 截断, "文件": 文件}


注册表.登记(
    代号="读材料",
    标题="读材料",
    说明="把一份材料的正文读出来（文本类直读，图片走本机 OCR），按字数截断。",
    参数=[
        {"代号": "文件", "标签": "材料文件名", "类型": "text", "必填": True,
         "示例": "第三课教案.docx"},
        {"代号": "最多字数", "标签": "最多返回多少字（默认 4000）", "类型": "number",
         "必填": False, "示例": 4000},
    ],
    处理函数=处理,
)
