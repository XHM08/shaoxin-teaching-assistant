
import os
import sys

from 地基 import 注册表

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from 能力 import _授权


def 处理(动作="查看", 档位="全部授权"):
    动作 = str(动作 or "查看").strip()
    if 动作 == "查看":
        现在 = _授权.自启档位()
        return {"提示": ("现在自启是：%s" % (现在 or "关")),
                "正文": ("自启＝没有窗口时自动开一个「%s」，让「跑命令」一段接一段跑。\n"
                        "现在：%s\n"
                        "测试期只有「全部授权」一档：开了就是窗口内命令一律放行（含禁用清单）。\n"
                        "收回、过期、条数用完之后不会再自动开。"
                        % (现在 or "—", 现在 or "关")),
                "自启": 现在, "条目": []}
    if 动作 == "关":
        值 = _授权.设自启("")
        return {"提示": "自启已关：现在没有窗口就会等你点。", "正文": "自启已关。", "自启": 值, "条目": []}
    if 动作 == "开":
        值 = _授权.设自启(str(档位 or "全部授权").strip())
        return {"提示": "自启已开：%s。没有窗口时会自动开一个，命令一段接一段跑。" % 值,
                "正文": ("自启已开：%s。\n没有窗口时会自动开一个窗口（不限时，条数按档位上限），"
                        "跑满或你收回后不再自动开。" % 值),
                "自启": 值, "条目": []}
    raise ValueError("「动作」只认 查看 / 开 / 关，现在给的是：" + 动作)


注册表.登记(
    代号="自启",
    标题="自启",
    说明="没有授权窗口时自动开一个，让命令一段接一段跑；只放行安全/普通两档。",
    参数=[
        {"代号": "动作", "标签": "查看 / 开 / 关", "类型": "text", "必填": False,
         "可选项": ["查看", "开", "关"]},
        {"代号": "档位", "标签": "开哪一档（测试期只有 全部授权）", "类型": "text", "必填": False,
         "可选项": ["全部授权"]},
    ],
    处理函数=处理,
)
