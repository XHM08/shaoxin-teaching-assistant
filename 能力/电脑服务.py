
import json
import time

from 地基 import 审计, 大模型, 提示词, 注册表

from 能力 import _电脑

一句话长度上限 = 200


def 动作条目(动作):
    return {"代号": 动作["代号"], "名称": 动作["名称"], "说明": 动作["说明"]}


def 清单条目():
    return [动作条目(动作) for 动作 in _电脑.动作清单]


def 清单文字():
    return "\n".join("- " + 动作["代号"] + "：" + 动作["名称"] + "（" + 动作["说明"] + "）"
                     for 动作 in _电脑.动作清单)


def 关键词命中(一句话):
    for 代号, 词表 in _电脑.关键词表.items():
        if any(词 in 一句话 for 词 in 词表):
            return 代号
    return ""


def 取出JSON(原文):
    起点 = 原文.find("{")
    终点 = 原文.rfind("}")
    if 起点 < 0 or 终点 <= 起点:
        return {}
    try:
        return json.loads(原文[起点:终点 + 1])
    except json.JSONDecodeError:
        return {}


def 模型理解(一句话, 开始时刻):
    提示词原文 = 提示词.填充(提示词.读取("电脑服务"),
                        动作清单=清单文字(), 老师的话=一句话)
    try:
        return 取出JSON(大模型.问(提示词原文))
    except Exception as 异常:
        审计.记一笔("电脑服务", {"阶段": "理解"}, 成功=False,
                    秒数=time.time() - 开始时刻, 备注=type(异常).__name__)
        raise


def 处理(一句话=""):
    开始时刻 = time.time()
    一句话 = str(一句话).strip()
    if len(一句话) > 一句话长度上限:
        raise ValueError("一句话太长了（最多 " + str(一句话长度上限) + " 个字）。")

    if not 一句话:
        return {"提示": "可以点下面的按钮，也可以直接用一句话说。",
                "正文": "", "条目": 清单条目()}

    代号 = 关键词命中(一句话)
    理由 = ""
    if not 代号:
        数据 = 模型理解(一句话, 开始时刻)
        代号 = str(数据.get("action", "")).strip()
        理由 = str(数据.get("why", "")).strip()

    动作 = _电脑.取动作(代号)
    if 动作 is None:
        return {"提示": "这句话没对上任何一个动作。",
                "正文": 理由 or "换个说法试试，例如「电脑好卡」「看看能清多少垃圾」「清空回收站」。",
                "条目": 清单条目()}

    要确认 = _电脑.要确认吗(动作["代号"])
    return {
        "提示": "听懂了：" + 动作["名称"] + (("　" + 理由) if 理由 else ""),
        "正文": ("这一步会真的动手，点「确认执行」我才做。" if 要确认
                 else "这一步只看不动，点「执行」就能看到结果。"),
        "条目": [动作条目(动作)],
        "动作": 动作["代号"],
        "需要确认": 要确认,
    }


def 处理执行(动作代号, 确认="否"):
    动作 = _电脑.取动作(str(动作代号).strip())
    if 动作 is None:
        raise ValueError("没有这个动作：" + str(动作代号) + "。可用的有："
                         + ", ".join(一条["代号"] for 一条 in _电脑.动作清单))
    代号 = 动作["代号"]
    要确认 = _电脑.要确认吗(代号)

    if 要确认 and str(确认).strip() != "是":
        信息, 文字 = _电脑.预览(代号)
        return {"提示": "先看清楚会发生什么，再决定要不要做。",
                "正文": 文字,
                "条目": [信息] if 信息 else [],
                "需要确认": True,
                "动作": 代号}

    开始时刻 = time.time()
    try:
        结果 = _电脑.处理表[代号]()
    except Exception as 异常:
        审计.记一笔("电脑服务", {"动作": 代号, "已确认": 要确认}, 成功=False,
                    秒数=time.time() - 开始时刻, 备注=type(异常).__name__)
        raise
    审计.记一笔("电脑服务", {"动作": 代号, "已确认": 要确认}, 成功=True,
                秒数=time.time() - 开始时刻)

    return {
        "提示": ("已执行：" if 要确认 else "看完了：") + 动作["名称"],
        "正文": "",
        "条目": 结果 if isinstance(结果, list) else [结果],
        "需要确认": False,
        "动作": 代号,
    }


注册表.登记(
    代号="电脑服务",
    标题="电脑服务",
    说明="用一句话说想干什么，系统对照固定的动作清单理解（不会自己发明动作）",
    参数=[{"代号": "一句话", "标签": "一句话（留空则列出所有动作）", "类型": "textarea",
           "必填": False, "示例": "例如：电脑好卡，帮我清一下垃圾"}],
    处理函数=处理,
)

注册表.登记(
    代号="执行电脑动作",
    标题="执行电脑动作",
    说明="执行某个动作；会动手的动作必须先传「确认=是」才真正执行",
    参数=[
        {"代号": "动作代号", "标签": "动作代号", "类型": "text", "必填": True,
         "示例": "例如：清临时文件"},
        {"代号": "确认", "标签": "确认（是 / 否）", "类型": "text", "必填": False,
         "可选项": ["否", "是"]},
    ],
    处理函数=处理执行,
)
