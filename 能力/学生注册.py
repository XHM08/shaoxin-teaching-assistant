
from 地基 import 审计, 注册表

from 能力 import _档案


def 处理注册(编号, 姓名, 学号="", 年级="", 班级="", 备注="", 家长同意书="未签回"):
    _档案.要求已签()
    for 名, 值 in (("编号", 编号), ("姓名", 姓名)):
        if not str(值).strip():
            raise ValueError(名 + "不能填空。")
    编号 = _档案.校验编号(编号)

    if _档案.已注册(编号):
        原名 = _档案.记资料(编号, 姓名, 学号, 年级, 班级, 备注, 家长同意书)
        现在 = str(姓名).strip()
        改动 = ("　姓名从「" + 原名 + "」改成「" + 现在 + "」") if 原名 and 原名 != 现在 else ""
        审计.记一笔("学生注册", {"编号": 编号, "动作": "改资料"}, 成功=True)
        return {
            "提示": "更新了 " + 编号 + " 的资料。" + 改动
                    + "（没填的字段保留原来的，不会被清空）",
            "正文": ("编号本来就在名册里，所以只改了对照表：没新建文件夹，也没动 "
                     + 编号 + " 已有的记录。\n对照表：" + _档案.对照表路径()),
            "条目": [],
        }

    编号 = _档案.注册(编号, 姓名, 学号, 年级, 班级, 备注, 家长同意书)
    审计.记一笔("学生注册", {"编号": 编号}, 成功=True)
    return {
        "提示": "已注册：" + 编号 + "（" + str(姓名).strip() + "）。",
        "正文": ("文件夹已建好：学生数据/" + 编号 + "/\n"
                 "姓名、年级、班级只写进了 学生数据/对照表/姓名对照表.json。"
                 "按《学生数据处理约定》二，对照表不属于采集数据、不发送给 AI 服务商，"
                 "也不会写进 " + 编号 + " 自己的记录。"),
        "条目": [],
    }


def 处理名册():
    if not _档案.同意书已签():
        return {"提示": "采集已阻断：监护人同意书尚未签署。", "条目": [], "正文": _档案.阻断说明}
    条目 = _档案.档案一览()
    return {
        "提示": "已注册 " + str(len(条目)) + " 人。",
        "条目": 条目,
        "正文": "" if 条目 else "还没有学生。在上面的框里填编号（如 S01）就能注册。",
    }


注册表.登记(
    代号="学生注册",
    标题="学生注册",
    说明="新增学生（编号与姓名等），或拿已注册的编号改资料。姓名只进对照表，不发送",
    参数=[
        {"代号": "编号", "标签": "学生编号（如 S01）", "类型": "text", "必填": True,
         "示例": "例如：S01"},
        {"代号": "姓名", "标签": "学生姓名", "类型": "text", "必填": True,
         "示例": "只写进对照表，不发送给 AI"},
        {"代号": "学号", "标签": "学号", "类型": "text", "必填": False,
         "示例": "同样只进对照表"},
        {"代号": "年级", "标签": "年级", "类型": "text", "必填": False,
         "示例": "例如：八年级"},
        {"代号": "班级", "标签": "班级", "类型": "text", "必填": False,
         "示例": "例如：3 班"},
        {"代号": "备注", "标签": "备注（别写电话、住址）", "类型": "textarea", "必填": False,
         "示例": "例如：家长 9/15 已签回同意书"},
        {"代号": "家长同意书", "标签": "家长同意书", "类型": "text", "必填": False,
         "可选项": ["已签回", "未签回"]},
    ],
    处理函数=处理注册,
)

注册表.登记(
    代号="学生名册",
    标题="学生名册",
    说明="查看已注册的学生（姓名来自对照表）与每人有多少条记录",
    参数=[],
    处理函数=处理名册,
)
