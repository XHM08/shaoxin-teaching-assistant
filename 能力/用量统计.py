
from 地基 import 审计, 注册表

读多少行 = 20000


def 是数字(值):
    return isinstance(值, (int, float)) and not isinstance(值, bool)


def 处理():
    全部 = 审计.读日志尾巴(读多少行)
    调用 = [一 for 一 in 全部 if 一.get("能力") == "模型调用"]
    没带缓存字段 = 0
    分组 = {}

    for 一 in 调用:
        元 = 一.get("元信息") or {}
        命中 = 元.get("缓存命中token")
        未命中 = 元.get("缓存未命中token")
        这次命中 = 命中 if 是数字(命中) else None
        这次未命中 = 未命中 if 是数字(未命中) else None
        if 这次命中 is None and 这次未命中 is None:
            没带缓存字段 += 1
            continue
        组 = 分组.setdefault(元.get("来源") or "（未标明）",
                            {"次数": 0, "命中": 0, "未命中": 0, "推理": 0})
        组["次数"] += 1
        组["命中"] += 这次命中 or 0
        组["未命中"] += 这次未命中 or 0
        组["推理"] += 元.get("推理token") if 是数字(元.get("推理token")) else 0

    条目 = []
    for 来源, 组 in 分组.items():
        总数 = 组["命中"] + 组["未命中"]
        条目.append({
            "来源": 来源,
            "计入的调用次数": 组["次数"],
            "命中token": 组["命中"],
            "未命中token": 组["未命中"],
            "推理token": 组["推理"],
            "命中率": ("%.1f%%" % (100.0 * 组["命中"] / 总数)) if 总数 else "—",
        })
    条目.sort(key=lambda 一: -一["未命中token"])

    命中合计 = sum(一["命中token"] for 一 in 条目)
    未命中合计 = sum(一["未命中token"] for 一 in 条目)
    推理合计 = sum(一["推理token"] for 一 in 条目)
    总数 = 命中合计 + 未命中合计

    说明 = ("读了日志最后 " + str(len(全部)) + " 行（最多取 " + str(读多少行) + " 条），其中模型调用 "
            + str(len(调用)) + " 次。")
    if 没带缓存字段:
        说明 += ("有 " + str(没带缓存字段)
                 + " 次响应里没带可用的缓存字段（服务商或中转站不报、或报的不是数字），没算进命中率。")

    注意事项 = (
        "几件容易误判的事，先说清楚：\n"
        "· 各家缓存字段叫法不同（DeepSeek 用 prompt_cache_hit_tokens，火山方舟用 "
        "prompt_tokens_details.cached_tokens），软件两种都认了；不报、或报的不是数字，"
        "一律计成「算不出」而不是 0% 命中。\n"
        "· 官方文档：前两次请求不会命中，第三次起才命中，刚跑一两次看到 0% 是正常的；"
        "缓存尽力而为，不保证 100%，闲置几小时到几天会自动清空。\n"
        "· 要提升命中率，靠的是「固定内容放前面、每次都变的内容放最后」。\n"
        "· 但缓存省的是输入。实测里真正的大头往往是输出：尤其推理模型"
        "（一句话的回答能烧掉上千推理 token）。看下面那列「推理 token」，"
        "它比缓存更值得先动。"
    )

    if not 条目:
        return {"提示": "还没有能算出命中率的模型调用。" + 说明,
                "条目": [], "正文": 注意事项}

    return {
        "提示": ("命中 " + str(命中合计) + " / 未命中 " + str(未命中合计)
                 + " token，合计命中率 "
                 + (("%.1f%%" % (100.0 * 命中合计 / 总数)) if 总数 else "—")
                 + "；推理 token " + str(推理合计) + "。" + 说明),
        "条目": 条目,
        "正文": ("下表按「未命中 token 从多到少」排。第一行就是最该先动的那条路径。\n" + 注意事项),
    }


注册表.登记(
    代号="用量统计",
    标题="用量统计",
    说明="看模型调用的缓存命中率，按发起的能力分行，哪条未命中最多排最前",
    参数=[],
    处理函数=处理,
)
