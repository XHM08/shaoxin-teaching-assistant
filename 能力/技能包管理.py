
from 地基 import 注册表
from 地基 import 技能包 as 技能包库


def 处理列表():
    条目 = 技能包库.技能包清单()
    return {
        "提示": "共 " + str(len(条目)) + " 份。",
        "条目": 条目,
        "正文": "" if 条目 else "还没有技能包，先去「教师蒸馏」生成一份。",
    }


def 处理查看(技能包):
    技能包库.校验代号(技能包)
    return {
        "提示": "技能包：" + 技能包,
        "正文": 技能包库.读技能包全文(技能包),
        "条目": [],
    }


注册表.登记(
    代号="技能包管理",
    标题="技能包管理",
    说明="查看已生成的技能包列表",
    参数=[],
    处理函数=处理列表,
)

注册表.登记(
    代号="查看技能包",
    标题="查看技能包",
    说明="查看某一份技能包的全文（SKILL.md）",
    参数=[{"代号": "技能包", "标签": "技能包代号", "类型": "text", "必填": True,
           "可选项来源": "技能包"}],
    处理函数=处理查看,
)
