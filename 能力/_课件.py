
import os

from 地基 import 幻灯片, 大模型, 提示词, 课件, 技能包, 配置


def 生成(技能包代号, 课题, 页数=8):
    提示词原文 = 提示词.填充(
        提示词.读取("课件生成"),
        技能包=技能包.读技能包全文(技能包代号),
        课题=课题,
        页数=str(页数).strip() or "8",
    )
    return 课件.取出JSON(大模型.问(提示词原文))


def 保存pptx(数据, 技能包代号, 课题):
    文件名 = 课件.安全文件名(技能包代号 + "-" + 课题) + ".pptx"
    输出目录 = 配置.取目录("课件输出")
    os.makedirs(输出目录, exist_ok=True)
    幻灯片.写出(数据, os.path.join(输出目录, 文件名))
    return 文件名
