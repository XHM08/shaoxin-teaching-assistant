
from 地基 import 审计, 材料, 注册表, 工具箱


def 处理列表():
    条目 = 材料.材料清单()
    return {
        "提示": "只列文件名与大小，不展示材料正文 —— 材料属教师本人。",
        "条目": 条目,
        "正文": "" if 条目 else "材料/ 目录下暂时没有材料（.txt / .md）。",
    }


def 工具_数字数(文件):
    原文 = 材料.读材料(材料.材料路径(文件))
    return {"文件": 文件, "字数": len(原文)}


注册表.登记(
    代号="材料台账",
    标题="材料台账",
    说明="查看 材料/ 目录下有哪些材料（不展示正文）",
    参数=[],
    处理函数=处理列表,
)

工具箱.登记工具(
    工具名="数材料字数",
    说明="数一份材料有多少字。只返回字数，不返回内容。",
    参数=[{"代号": "文件", "标签": "材料文件名"}],
    处理函数=工具_数字数,
)

审计.记一笔("材料台账.登记工具", {"工具": "数材料字数"}, 成功=True)
