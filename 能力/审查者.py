
from 地基 import 注册表, 审查记录

最多上限 = 200


def _数(最多):
    try:
        数 = int(最多)
    except (TypeError, ValueError):
        raise ValueError("「最多几条」要写整数，比如 50")
    if 数 < 1:
        raise ValueError("「最多几条」不能小于 1，现在是 %d" % 数)
    return min(数, 最多上限)


def 处理(动作="查看", 最多=50, 确认清空=""):
    动作 = str(动作 or "查看").strip()
    if 动作 == "清空":
        if str(确认清空 or "").strip() != "确认清空":
            raise ValueError("清空审查记录要把「确认清空」四个字填进确认框，防手滑")
        删了 = 审查记录.清空()
        return {"正文": "审查记录已清空（删了 %d 条）。" % 删了, "条目": [], "条数": 0,
                "统计": 审查记录.统计()}
    if 动作 != "查看":
        raise ValueError("动作只认「查看」或「清空」，现在是「%s」" % 动作)

    要几 = _数(最多)
    最近 = 审查记录.取最近(要几)
    总计 = 审查记录.统计()
    行们 = []
    for 一 in 最近:
        问题们 = 一.get("问题们") or []
        行们.append({
            "时间": 一.get("时间", ""),
            "判定": 一.get("判定", ""),
            "老师说的": 一.get("老师说的", ""),
            "问题数": len(问题们),
            "问题们": [{"级别": 问.get("级别", ""), "说明": 问.get("说明", ""),
                     "位置": 问.get("位置", "")} for 问 in 问题们],
            "回答字数": 一.get("回答字数", 0),
            "工具次数": 一.get("工具次数", 0),
        })

    if not 最近:
        正文 = ("还没有记录。审查者只在创造模式里真动过东西、或回答超过 400 字时才跑，"
                "纯闲聊不会有记录。")
    else:
        正文 = ("本次列出最近 %d 轮，其中挑出 %d 条问题。"
                "全库共 %d 轮：通过 %d、有问题 %d、跳过 %d（回答短或纯闲聊，省一轮钱）、没跑成 %d，"
                "累计 %d 条问题。"
                % (len(行们), sum(一["问题数"] for 一 in 行们),
                   总计["总轮数"], 总计.get("通过轮数", 0), 总计["有问题轮数"],
                   总计.get("跳过轮数", 0), 总计["没跑成轮数"], 总计["问题条数"]))
    return {"正文": 正文, "条目": 行们, "统计": 总计, "条数": len(行们)}


注册表.登记(
    代号="审查者",
    标题="审查者",
    说明="看审查者这些轮挑出过什么：判定、问题、原问题摘要。审查只报告，不改答案。",
    参数=[
        {"代号": "动作", "标签": "动作（查看 / 清空）", "类型": "text", "必填": False,
         "可选项": ["查看", "清空"], "示例": "查看"},
        {"代号": "最多", "标签": "最多列出几轮", "类型": "number", "必填": False, "示例": 50},
        {"代号": "确认清空", "标签": "清空时把「确认清空」填进来", "类型": "text",
         "必填": False, "示例": "确认清空"},
    ],
    处理函数=处理,
)
