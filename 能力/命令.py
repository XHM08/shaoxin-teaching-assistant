
import time

from 地基 import 审计, 配置, 注册表

from 能力 import _命令


def _限制():
    命令配置 = 配置.读取().get("命令", {})
    return bool(命令配置.get("需要确认", True)), int(命令配置.get("超时秒数", 60))


def 处理(命令, 工作目录=""):
    文本 = _命令.检查(命令)
    需要确认, 超时秒数 = _限制()
    运行目录 = 工作目录 or 配置.根目录
    编号 = _命令.登记(文本)
    return {
        "提示": "这是要跑的命令，还没执行。",
        "正文": _命令.预览文字(文本, 运行目录, 超时秒数) + "\n\n确认编号：" + 编号,
        "条目": [],
        "命令": 文本,
        "编号": 编号,
        "需要确认": 需要确认,
        "风险": _命令.风险提示(文本),
    }


def 处理执行(命令, 工作目录="", 确认="否", 编号=""):
    文本 = _命令.检查(命令)
    需要确认, 超时秒数 = _限制()
    运行目录 = 工作目录 or 配置.根目录

    if 需要确认 and str(确认).strip() != "是":
        return {
            "提示": "已拒绝执行：没有明确确认。",
            "正文": _命令.预览文字(文本, 运行目录, 超时秒数),
            "条目": [],
            "命令": 文本,
            "需要确认": True,
            "风险": _命令.风险提示(文本),
        }

    if not str(编号).strip():
        return {
            "提示": "已拒绝执行：缺少确认编号。",
            "正文": "先让 AI 提出这条命令（或调「看一条命令」），拿到确认编号，用它确认。",
            "条目": [],
            "命令": 文本,
            "需要确认": True,
        }
    _命令.取票(编号, 文本)

    开始时刻 = time.time()
    结果 = _命令.运行(文本, 运行目录, 超时秒数)
    审计.记一笔("命令", {"退出码": 结果["退出码"], "命令": 文本[:200]},
                成功=(结果["退出码"] == 0), 秒数=time.time() - 开始时刻)

    return {
        "提示": "执行完毕（退出码 " + str(结果["退出码"]) + "）",
        "正文": 结果["输出"],
        "条目": [],
        "命令": 文本,
        "需要确认": False,
    }


注册表.登记(
    代号="看一条命令",
    标题="看一条命令",
    说明="检查并预览一条命令（不执行）",
    参数=[
        {"代号": "命令", "标签": "命令", "类型": "textarea", "必填": True},
        {"代号": "工作目录", "标签": "在哪个目录执行（留空 = 项目目录）", "类型": "text", "必填": False},
    ],
    处理函数=处理,
)

注册表.登记(
    代号="执行命令",
    标题="执行命令",
    说明="执行一条命令；默认必须先传「确认=是」",
    参数=[
        {"代号": "命令", "标签": "命令", "类型": "textarea", "必填": True},
        {"代号": "工作目录", "标签": "在哪个目录执行（留空 = 项目目录）", "类型": "text", "必填": False},
        {"代号": "确认", "标签": "确认（是 / 否）", "类型": "text", "必填": False,
         "可选项": ["否", "是"]},
        {"代号": "编号", "标签": "确认编号（界面自动带，不用手填）", "类型": "text", "必填": False},
    ],
    处理函数=处理执行,
)
