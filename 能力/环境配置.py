
import time

from 地基 import 审计, 注册表

from 能力 import _环境


def 处理(环境代号=""):
    环境代号 = str(环境代号).strip()
    if not 环境代号:
        条目 = _环境.清单()
        已就绪 = sum(1 for 一条 in 条目 if 一条["状态"] == "已就绪")
        没配齐 = [一条["环境"] for 一条 in 条目 if 一条["状态"] != "已就绪"]
        提示 = "共 " + str(len(条目)) + " 项，已就绪 " + str(已就绪) + " 项。"
        if 没配齐:
            提示 += "还没配齐：" + "、".join(没配齐)
        return {"提示": 提示, "正文": "", "条目": 条目}

    环境项 = _环境.取环境项(环境代号)
    if 环境项 is None:
        raise ValueError("没有这个环境项：" + 环境代号 + "。可用的有："
                         + ", ".join(一项["id"] for 一项 in _环境.环境清单))

    可用, 说明 = _环境.检测(环境项["id"])
    指引 = "" if 可用 else _环境.手动提示(环境项["id"])
    return {
        "提示": 环境项["名称"] + "：" + ("已就绪" if 可用 else "未配齐"),
        "正文": 说明 or 指引 or "这台电脑上没找到，可以点「安装」用 winget 装。",
        "条目": [_环境.方案(环境项["id"])],
        "环境项": 环境项["id"],
        "需要确认": bool(not 可用 and 环境项.get("winget")),
    }


def 处理安装(环境代号, 确认="否"):
    环境项 = _环境.取环境项(str(环境代号).strip())
    if 环境项 is None:
        raise ValueError("没有这个环境项：" + str(环境代号) + "。可用的有："
                         + ", ".join(一项["id"] for 一项 in _环境.环境清单))
    名字 = 环境项["id"]
    可用, 说明 = _环境.检测(名字)

    if 可用:
        return {"提示": 环境项["名称"] + " 已经装好了，不用再装。", "正文": 说明,
                "条目": [_环境.方案(名字)], "需要确认": False, "环境项": 名字}

    if not 环境项.get("winget"):
        return {"提示": 环境项["名称"] + " 需要你手动装，本系统不代劳。",
                "正文": _环境.手动提示(名字), "条目": [_环境.方案(名字)],
                "需要确认": False, "环境项": 名字}

    if str(确认).strip() != "是":
        return {
            "提示": "先看清楚要装什么，再决定。",
            "正文": ("将通过 winget 安装 " + 环境项["名称"] + "（包名 " + 环境项["winget"] + "）。\n"
                     "需要联网，可能要几分钟；如果弹出管理员授权窗，请点「是」。\n"
                     "装完可能要把本系统关掉重开，这里才会检测到。\n"
                     "按下「确认安装」才会真正开始。"),
            "条目": [_环境.方案(名字)],
            "需要确认": True,
            "环境项": 名字,
        }

    开始时刻 = time.time()
    try:
        结果 = _环境.安装(名字)
    except Exception as 异常:
        审计.记一笔("环境配置", {"环境项": 名字}, 成功=False,
                    秒数=time.time() - 开始时刻, 备注=type(异常).__name__)
        raise
    审计.记一笔("环境配置", {"环境项": 名字, "退出码": 结果["退出码"]},
                成功=(结果["结果"] == "成功"), 秒数=time.time() - 开始时刻)

    return {
        "提示": "安装" + 结果["结果"] + "：" + 环境项["名称"],
        "正文": 结果["输出末尾"],
        "条目": [结果],
        "需要确认": False,
        "环境项": 名字,
    }


注册表.登记(
    代号="环境配置",
    标题="环境配置",
    说明="检测这台电脑上的 Python / Node / Git / VS Code / WSL，缺的可以用 winget 装",
    参数=[{"代号": "环境代号", "标签": "只看某一项（留空则全部检测）", "类型": "text",
           "必填": False, "示例": "例如：python"}],
    处理函数=处理,
)

注册表.登记(
    代号="安装环境",
    标题="安装环境",
    说明="用 winget 安装某个环境；必须先传「确认=是」才真正开始安装",
    参数=[
        {"代号": "环境代号", "标签": "环境代号", "类型": "text", "必填": True,
         "可选项": [一项["id"] for 一项 in _环境.环境清单]},
        {"代号": "确认", "标签": "确认（是 / 否）", "类型": "text", "必填": False,
         "可选项": ["否", "是"]},
    ],
    处理函数=处理安装,
)
