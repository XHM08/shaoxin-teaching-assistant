
import os
import time

from 地基 import 审计, 课件, 课件图, 注册表, 配置

from 能力 import _课件, 讲稿配音

参数表 = [
    {"代号": "技能包", "标签": "用哪位教师的讲法", "类型": "text", "必填": True,
     "可选项来源": "技能包"},
    {"代号": "课题", "标签": "课题", "类型": "text", "必填": True,
     "示例": "例如：分数的除法"},
    {"代号": "页数", "标签": "页数（默认 6）", "类型": "text", "必填": False},
    {"代号": "要不要配音", "标签": "要不要配音（默认要；填“不”则跳过）", "类型": "text", "必填": False},
]


def 处理(技能包, 课题, 页数="6", 要不要配音="要"):
    开始时刻 = time.time()
    上下文 = _课件.上下文表()
    try:
        数据 = _课件.生成(技能包, 课题, 页数, 上下文)
    except Exception as 异常:
        审计.记一笔("联动教学", {"课题字数": len(课题)}, 成功=False,
                    秒数=time.time() - 开始时刻, 备注=type(异常).__name__)
        raise

    文件名 = _课件.保存pptx(数据, 技能包, 课题, 上下文)

    页图表 = {}
    try:
        位置 = 课件图.导出各页(os.path.join(配置.取目录("课件输出"), 文件名), 上下文["警告"])
        页图表 = {序号: 课件图.页图地址(位置["目录名"], 序号)
                 for 序号 in range(1, 位置["页数"] + 1)}
    except Exception as 异常:
        上下文["警告"].append("没导出每页图（" + type(异常).__name__ + "："
                        + str(异常).splitlines()[0][:60]
                        + "）—— 上课时**每一页**都只能用文字版显示")

    配音目录 = ""
    音频表 = {}
    配音说明 = ""
    配音用时 = 0.0
    if 讲稿配音.要配音吗(要不要配音):
        能, 原因 = 讲稿配音.能配音吗()
        if not 能:
            配音说明 = "没配音（" + 原因 + "）"
        else:
            警告 = []
            配音开始 = time.time()
            try:
                配音目录, 配音条目 = 讲稿配音.合成整份(
                    os.path.join(配置.取目录("课件输出"), 文件名), 讲稿配音.取配置语速(), 警告)
                音频表 = {条["页"]: 条["音频"] for 条 in 配音条目}
                配音用时 = time.time() - 配音开始
                总页数 = len(课件.页面清单(数据))
                if len(音频表) >= 总页数:
                    配音说明 = "每页都配了音（翻开哪页就播哪页，配音用了 %.0f 秒）" % 配音用时
                else:
                    配音说明 = ("配了 %d / %d 页（其余页没有讲稿，翻到那页没有声音）"
                             % (len(音频表), 总页数))
                for 一句 in 警告:
                    配音说明 += "；" + 一句
            except Exception as 异常:
                配音说明 = "配音没成（" + str(异常).splitlines()[0][:70] + "）"
                配音用时 = time.time() - 配音开始
                审计.记一笔("联动教学", {"课件": 文件名}, 成功=False,
                            秒数=配音用时, 备注="配音失败：" + type(异常).__name__)

    条目 = []
    for 序号, 一页 in enumerate(课件.页面清单(数据), 1):
        条目.append({
            "页": 序号,
            "标题": str(一页.get("title", "")),
            "要点": 课件.要点成行(一页.get("points")),
            "讲稿": str(一页.get("script", "")),
            "音频": 音频表.get(序号, ""),
            "页图": 页图表.get(序号, ""),
        })

    审计.记一笔("联动教学", {"页数": len(条目), "配图页数": len(上下文["配图页"]),
                        "配音页数": len(音频表), "页图页数": len(页图表)}, 成功=True,
                秒数=time.time() - 开始时刻)
    提示 = "可以开始上课了（共 " + str(len(条目)) + " 页）"
    追加 = []
    if 上下文["配图页"]:
        追加.append("第 " + "、".join(str(号) for 号 in 上下文["配图页"]) + " 页配了图")
    if 配音说明:
        追加.append(配音说明)
    追加 += list(上下文["警告"][:3])
    if 追加:
        提示 += "；" + "；".join(追加)
    return {
        "提示": 提示,
        "正文": "",
        "条目": 条目,
        "课件文件": 文件名,
        "课名": str(数据.get("title", 课题)),
        "配音目录": 配音目录,
    }


注册表.登记(
    代号="联动教学",
    标题="联动教学",
    说明="按某位教师的讲法生成整课（每页要点 + 讲稿），同时也出一份 .pptx",
    参数=参数表,
    处理函数=处理,
)
