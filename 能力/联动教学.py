
import time

from 地基 import 审计, 课件, 注册表

from 能力 import _课件

参数表 = [
    {"代号": "技能包", "标签": "用哪位教师的讲法", "类型": "text", "必填": True,
     "可选项来源": "技能包"},
    {"代号": "课题", "标签": "课题", "类型": "text", "必填": True,
     "示例": "例如：分数的除法"},
    {"代号": "页数", "标签": "页数（默认 6）", "类型": "text", "必填": False},
]


def 处理(技能包, 课题, 页数="6"):
    开始时刻 = time.time()
    try:
        数据 = _课件.生成(技能包, 课题, 页数)
    except Exception as 异常:
        审计.记一笔("联动教学", {"课题字数": len(课题)}, 成功=False,
                    秒数=time.time() - 开始时刻, 备注=type(异常).__name__)
        raise

    文件名 = _课件.保存pptx(数据, 技能包, 课题)
    条目 = []
    for 序号, 一页 in enumerate(课件.页面清单(数据), 1):
        条目.append({
            "页": 序号,
            "标题": str(一页.get("title", "")),
            "要点": "\n".join(str(一条) for 一条 in (一页.get("points") or [])),
            "讲稿": str(一页.get("script", "")),
        })

    审计.记一笔("联动教学", {"页数": len(条目)}, 成功=True,
                秒数=time.time() - 开始时刻)
    return {
        "提示": "可以开始上课了（共 " + str(len(条目)) + " 页）。",
        "正文": "",
        "条目": 条目,
        "课件文件": 文件名,
        "课名": str(数据.get("title", 课题)),
    }


注册表.登记(
    代号="联动教学",
    标题="联动教学",
    说明="按某位教师的讲法生成整课（每页要点 + 讲稿），同时也出一份 .pptx",
    参数=参数表,
    处理函数=处理,
)
