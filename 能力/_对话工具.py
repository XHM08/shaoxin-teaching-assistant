_本线程 = threading.local()


def _开始一轮():
    _本线程.待确认 = []


def _收取待确认():
    return list(getattr(_本线程, "待确认", []))


def 带工具跑一轮(提示词, 问模型, 调用记录):
    _开始一轮()
    回答 = 工具箱.带工具跑(提示词, 问模型, 调用记录=调用记录)
    return 回答, _收取待确认()


def 登记命令(命令, 为什么=""):
    超时秒数 = int(配置.读取().get("命令", {}).get("超时秒数", 60))
    认定 = _授权.跑一条(_授权.当前会话(), 命令, 配置.根目录, 超时秒数)

    if 认定["动作"] == "自动":
        结果 = 认定["结果"]
        尾巴 = "（注意：这一档连禁用清单也放行了）" if 认定["放行禁用清单"] else ""
        return {"已执行": True, "退出码": 结果["退出码"], "输出": 结果["输出"],
                "提示": 认定["为什么"] + "，输出在下面" + 尾巴}

    if 认定["动作"] == "拒绝":
        return {"已执行": False,
                "提示": 认定["为什么"] + "。换一种做法，不要重试同一条。"}

    try:
        文本 = _命令.检查(命令)
    except ValueError as 异常:
        return {"已执行": False, "提示": str(异常) + "。换一种做法，不要重试同一条。"}
    待确认 = getattr(_本线程, "待确认", None)
    if 待确认 is None:
        raise RuntimeError("当前没有正在进行的对话，命令无法登记。")
    编号 = _命令.登记(文本)
    待确认.append({"命令": 文本, "为什么": str(为什么 or ""),
                   "风险": _命令.风险提示(文本), "编号": 编号})
    return {"已登记的待确认命令": 文本, "确认编号": 编号,
            "提示": "这条命令还没执行，要等老师在界面上点「执行这条命令」才会跑。"
                    "原因：" + 认定["为什么"],
            "为什么没自动跑": 认定["为什么"]}


