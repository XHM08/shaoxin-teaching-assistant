def _绑能力(能力代号):
    def 调用(**实参):
        return 注册表.取能力(能力代号)["处理函数"](**实参)
    调用.__绑定能力__ = 能力代号
    return 调用


def _登记全部():
    for 工具名, 说明, 参数, 能力代号 in 能力绑定:
        if 工具名 in 工具箱.已登记工具:
            continue
        工具箱.登记工具(工具名, 说明, 参数, _绑能力(能力代号))

    for 工具名, 说明, 参数, 处理函数 in 直接工具:
        if 工具名 in 工具箱.已登记工具:
            continue
        工具箱.登记工具(工具名, 说明, 参数, 处理函数)


