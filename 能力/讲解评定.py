
import time

from 地基 import 审计, 大模型, 提示词, 注册表
from 地基 import 技能包 as 技能包库

from 能力 import _评定



def 处理出讲解(技能包, 题目):
    开始时刻 = time.time()
    技能包库.校验代号(技能包)
    if not str(题目).strip():
        raise ValueError("题目不能为空。")

    提示词原文 = 提示词.填充(提示词.读取("讲解评定"),
                        教师档案=技能包库.读技能包全文(技能包),
                        题目=str(题目).strip())
    try:
        讲解 = 大模型.问(提示词原文)
    except Exception as 异常:
        审计.记一笔("讲解评定", {"技能包": 技能包}, 成功=False,
                    秒数=time.time() - 开始时刻, 备注=type(异常).__name__)
        raise

    号 = _评定.记待评(str(题目).strip(), 技能包, 讲解)
    审计.记一笔("讲解评定", {"技能包": 技能包, "条目号": 号}, 成功=True,
                秒数=time.time() - 开始时刻)
    return {
        "提示": "已生成第 " + str(号) + " 条待评。请老师看这段讲解「对不对」，"
                "再点下面的判定 —— 这一步就是教师审核闭环，"
                "研究里要拿他的改版和 AI 原版做盲评对照。",
        "正文": 讲解,
        "条目": [],
        "条目号": 号,
    }


def 处理记评定(条目号, 判定, 改后讲解="", 老师原话=""):
    原文 = str(条目号).strip()
    if not 原文.isdigit():
        raise ValueError("条目号要写数字，比如 3。拿到的是：" + (原文 or "（空）"))
    号 = int(原文)
    已有 = _评定.已有条目号()
    if 号 not in 已有:
        raise ValueError("没有第 " + str(号) + " 条待评。现在有的条目号是："
                         + ("、".join(str(一) for 一 in sorted(已有)) or "（一条都没有）"))
    _评定.记评定(号, str(判定).strip(), 改后讲解, 老师原话)
    审计.记一笔("记讲解评定", {"条目号": 号, "判定": str(判定).strip()}, 成功=True)
    return {
        "提示": "第 " + str(号) + " 条已记为「" + str(判定).strip() + "」。"
                + ("改后的版本也存下了。" if str(改后讲解 or "").strip()
                   else "（没填改后的版本，盲评时这一条只进未审核版那一组。）"),
        "正文": "",
        "条目": [],
    }


def 处理台账(只看="全部"):
    范围 = str(只看 or "全部").strip()
    if 范围 not in ("全部", "待评", "已评"):
        raise ValueError("「只看」只能是：全部 / 待评 / 已评。拿到的是：" + 范围)
    条 = _评定.台账()
    if 范围 != "全部":
        条 = [一 for 一 in 条 if 一["状态"] == 范围]
    条目 = [{
        "条目号": 一["条目号"],
        "状态": 一["状态"],
        "判定": 一["判定"],
        "题目": 一["题目"],
        "讲解A": 一["讲解A"],
        "讲解B": 一["讲解B"],
        "老师原话": 一["老师原话"],
        "时间": 一["时间"],
    } for 一 in 条]
    return {
        "提示": "共 " + str(len(条)) + " 条（" + 范围 + "）。"
                "这份台账里没有任何学生信息 —— 题目由项目组自备，不经学生。",
        "条目": 条目,
        "正文": "",
    }


