
import time

from 地基 import 审计, 课件, 注册表

from 能力 import _课件

参数表 = [
    {"代号": "技能包", "标签": "用哪位教师的风格", "类型": "text", "必填": True,
     "可选项来源": "技能包"},
    {"代号": "课题", "标签": "课题", "类型": "text", "必填": True,
     "示例": "例如：分数的除法"},
    {"代号": "页数", "标签": "页数（默认 8）", "类型": "text", "必填": False},
]


def 处理(技能包, 课题, 页数="8"):
    开始时刻 = time.time()
    try:
        数据 = _课件.生成(技能包, 课题, 页数)
    except Exception as 异常:
        审计.记一笔("课件生成", {"课题字数": len(课题)}, 成功=False,
                    秒数=time.time() - 开始时刻, 备注=type(异常).__name__)
        raise

    文件名 = _课件.保存pptx(数据, 技能包, 课题)
    审计.记一笔("课件生成", {"页数": len(课件.页面清单(数据))}, 成功=True,
                秒数=time.time() - 开始时刻)
    return {
        "提示": "课件已生成：" + 文件名,
        "正文": 课件.转文字(数据),
        "条目": [],
        "课件文件": 文件名,
    }


注册表.登记(
    代号="课件生成",
    标题="PPT 生成",
    说明="按某位教师的技能包风格，生成一份 PowerPoint 课件（.pptx，讲稿放在备注里）",
    参数=参数表,
    处理函数=处理,
)
