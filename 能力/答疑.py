
import time

from 地基 import 审计, 大模型, 提示词, 注册表
from 地基 import 技能包 as 技能包库


def 处理(技能包, 问题):
    开始时刻 = time.time()
    技能包库.校验代号(技能包)
    if not 问题.strip():
        raise ValueError("问题不能为空")

    提示词原文 = 提示词.填充(提示词.读取("答疑"),
                        教师档案=技能包库.读技能包全文(技能包), 问题=问题)

    try:
        回答 = 大模型.问(提示词原文)
    except Exception as 异常:
        审计.记一笔("答疑", {"提问字数": len(问题)}, 成功=False,
                    秒数=time.time() - 开始时刻, 备注=type(异常).__name__)
        raise

    审计.记一笔("答疑", {"技能包": 技能包, "提问字数": len(问题)},
                成功=True, 秒数=time.time() - 开始时刻)
    return {
        "提示": "回答完成。本次提问未被记录（只记了长度）。",
        "正文": 回答,
        "条目": [],
    }


注册表.登记(
    代号="答疑",
    标题="学生答疑",
    说明="用某位老师的技能包回答问题（带上他的讲法）",
    参数=[
        {"代号": "技能包", "标签": "选择教师技能包", "类型": "text", "必填": True,
         "可选项来源": "技能包"},
        {"代号": "问题", "标签": "学生的问题", "类型": "textarea", "必填": True,
         "示例": "例如：老师，为什么除以分数要倒过来乘？"},
    ],
    处理函数=处理,
)
