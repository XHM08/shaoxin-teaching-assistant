
import threading
import time

from 地基 import 审计, 配置

from 能力 import _命令

档位表 = {
    "安全授权": 30,
    "普通授权": 60,
    "全部授权": 120,
}
档位列表 = ("安全授权", "普通授权", "全部授权")
不限时 = "不限"
会话表上限 = 200
分钟上限 = 60 * 24 * 7
结束留存秒数 = 600

_锁 = threading.Lock()
_表 = {}
_本线程 = threading.local()


def 设当前会话(会话):
    _本线程.会话 = str(会话 or "")


def 清当前会话():
    _本线程.会话 = ""


def 当前会话():
    return getattr(_本线程, "会话", "")


def _结束(值, 原因, 现在):
    值["结束原因"] = 原因
    值["结束时刻"] = 现在


def _回收(现在):
    能清的 = [会话 for 会话, 值 in _表.items()
             if 值["结束原因"] and 现在 - 值["结束时刻"] > 结束留存秒数]
    for 会话 in 能清的:
        _表.pop(会话, None)

    被淘汰 = []
    while len(_表) > 会话表上限:
        最旧 = min(_表, key=lambda 键: _表[键]["开窗时刻"])
        被淘汰.append(_表[最旧]["档位"])
        _表.pop(最旧, None)
    return 被淘汰


def _记淘汰(被淘汰):
    for 档位 in 被淘汰:
        审计.记一笔("长任务授权", {"档位": 档位, "动作": "配额淘汰"}, 成功=False)


def 默认档位():
    值 = str(配置.读取().get("命令", {}).get("默认档位", "") or "").strip()
    return 值 if 值 in 档位表 else ""


def _状态_持锁中(会话, 现在):
    会话 = str(会话 or "")
    空 = {"档位": "", "剩余秒": 0, "剩余几条": 0, "不限时": False,
         "结束原因": "", "说明": ""}
    值 = _表.get(会话)
    if 值 is None:
        缺省 = 默认档位()
        if 缺省:
            return dict(空, 档位=缺省, 剩余秒=-1, 剩余几条=档位表[缺省], 不限时=True,
                        说明="默认档位（测试期）")
        return dict(空, 结束原因="没有窗口")
    if 值["结束原因"]:
        return dict(空, 结束原因=值["结束原因"])
    if 现在 >= 值["到点"]:
        _结束(值, "窗口已过期", 现在)
        return dict(空, 结束原因="窗口已过期")
    上限条 = 档位表[值["档位"]]
    剩余条 = 上限条 - 值["用了几条"]
    if 剩余条 <= 0:
        _结束(值, "窗口已用完", 现在)
        return dict(空, 结束原因="窗口已用完")
    不限 = 值["到点"] == float("inf")
    return dict(空, 档位=值["档位"],
                剩余秒=-1 if 不限 else max(0, int(值["到点"] - 现在)),
                剩余几条=剩余条, 不限时=不限)


def 查授权(会话):
    现在 = time.time()
    with _锁:
        被淘汰 = _回收(现在)
        结果 = _状态_持锁中(会话, 现在)
    _记淘汰(被淘汰)
    return 结果


def 收回(会话):
    会话 = str(会话 or "")
    现在 = time.time()
    档位 = ""
    with _锁:
        被淘汰 = _回收(现在)
        值 = _表.get(会话)
        if 值 is not None and not 值["结束原因"]:
            档位 = 值["档位"]
            _结束(值, "窗口已收回", 现在)
    _记淘汰(被淘汰)
    if 档位:
        审计.记一笔("长任务授权", {"档位": 档位, "动作": "收回"}, 成功=True)
    return 查授权(会话)


def 开授权(档位, 分钟, 会话=""):
    会话 = str(会话 or "")
    if not 会话:
        raise ValueError("没有会话标识，开不了长任务授权（请在网页的「创造模式」里开）。")
    if not str(档位 or "").strip():
        return 查授权(会话)
    if 档位 not in 档位表:
        raise ValueError("档位只能是：" + " / ".join(档位列表))
    原文 = str(分钟).strip()
    不限 = (原文 == 不限时)
    if not 不限:
        try:
            分钟数 = int(原文 or "0")
        except ValueError:
            raise ValueError("分钟要么是整数（0 / 5 / 10 / 15 / 30），要么是「不限」。") from None
        if 分钟数 <= 0:
            return 收回(会话)
        if 分钟数 > 分钟上限:
            raise ValueError("分钟最多 " + str(分钟上限) + "（一周）。要做更久的事，请用「不限」。")
    现在 = time.time()
    到点 = float("inf") if 不限 else 现在 + 分钟数 * 60
    with _锁:
        被淘汰 = _回收(现在)
        旧 = _表.get(会话)
        _表[会话] = {"档位": 档位, "到点": 到点, "用了几条": 0,
                   "开窗时刻": 现在, "结束原因": "", "结束时刻": 0}
    _记淘汰(被淘汰)
    审计.记一笔("长任务授权", {"档位": 档位, "不限时": 不限,
                            "分钟": (0 if 不限 else 分钟数),
                            "替换了": (旧["档位"] if 旧 else ""),
                            "会放行禁用清单": 档位 == "全部授权"}, 成功=True)
    return 查授权(会话)


def 跑一条(会话, 命令文本, 工作目录, 超时秒数):
    文本 = _命令.检查基本(命令文本)
    撞了 = _命令.撞了禁用清单(文本)
    风险 = _命令.风险提示(文本)
    现在 = time.time()
    档位 = ""
    原因 = ""
    with _锁:
        被淘汰 = _回收(现在)
        状态 = _状态_持锁中(会话, 现在)
        档位 = 状态["档位"]
        原因 = 状态["结束原因"]
        值 = _表.get(str(会话 or ""))
        if 撞了 and 档位 != "全部授权":
            结果 = {"动作": "拒绝", "放行禁用清单": False, "结果": {},
                    "为什么": "这条命令被禁止（" + 撞了 + "）"
                            + ("；当前" + 原因 if 原因 else "；这一档也不放行禁用清单")
                            + "：" + 文本}
        elif 原因:
            结果 = {"动作": "待确认", "为什么": 原因, "放行禁用清单": False, "结果": {}}
        elif 风险 and 档位 == "安全授权":
            结果 = {"动作": "待确认", "为什么": "安全授权下命中危险行为",
                    "放行禁用清单": False, "结果": {}}
        else:
            if 值 is not None:
                值["用了几条"] += 1
            放行 = bool(撞了)
            结果 = None
    _记淘汰(被淘汰)

    if 结果 is not None:
        return 结果

    开始时刻 = time.time()
    运行结果 = _命令.运行(文本, 工作目录, 超时秒数)
    审计.记一笔("命令", {"退出码": 运行结果["退出码"], "命令": 文本[:200],
                      "档位": 档位, "放行禁用清单": 放行},
                成功=(运行结果["退出码"] == 0), 秒数=time.time() - 开始时刻)
    return {"动作": "自动", "为什么": "在「" + 档位 + "」窗口内自动执行",
            "放行禁用清单": 放行, "结果": 运行结果}
