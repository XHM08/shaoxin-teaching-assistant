
import os
import re

from 地基 import 审计, 配置, 注册表
from 地基 import 技能包 as 技能包库

from 能力 import _评定

节标题行 = re.compile(r"^##\s+(.*\S)\s*$")


def 读原始(代号):
    目录 = 技能包库.技能包目录(代号)
    if not os.path.isdir(目录):
        raise ValueError("没有这个技能包：" + 代号)
    路径 = os.path.join(目录, "SKILL.md")
    if not os.path.isfile(路径):
        raise ValueError("这个技能包里没有 SKILL.md：" + 路径)
    with open(路径, "r", encoding="utf-8") as 文件:
        return 路径, 文件.read()


def 拆节(原文):
    有末换行 = 原文.endswith("\n")
    节们 = []
    前置行们 = []
    当前 = None
    for 行 in 原文.splitlines():
        匹配 = 节标题行.match(行)
        if 匹配:
            if 当前 is not None:
                节们.append(当前)
            当前 = {"标题": 匹配.group(1), "标题行": 行, "行们": []}
        elif 当前 is None:
            前置行们.append(行)
        else:
            当前["行们"].append(行)
    if 当前 is not None:
        节们.append(当前)
    return 前置行们, 节们, 有末换行


def 拼回(前置行们, 节们, 改标题=None, 新内容="", 有末换行=False):
    行们 = list(前置行们)
    for 节 in 节们:
        行们.append(节["标题行"])
        if 改标题 is not None and 节["标题"] == 改标题:
            行们.extend(str(新内容).strip("\n").splitlines())
        else:
            行们.extend(节["行们"])
    原文 = "\n".join(行们)
    return 原文 + "\n" if 有末换行 else 原文


def 处理看节(技能包):
    技能包库.校验代号(技能包)
    路径, 原文 = 读原始(技能包)
    _, 节们, _ = 拆节(原文)
    if not 节们:
        raise ValueError("这份技能包里一段（## 开头的）都没有，没法逐段校订：\n" + 路径)
    条目 = [{"节号": 序, "标题": 节["标题"],
             "原文": "\n".join(节["行们"]).strip()}
            for 序, 节 in enumerate(节们, 1)]
    return {
        "提示": "这份技能包有 " + str(len(节们)) + " 段。逐段过一遍："
                "讲得对的就不用动，要改就写一版再存回去 —— "
                "存之前会自动把改前那一版备份到 技能包\\" + 技能包 + "\\_历史\\。",
        "条目": 条目,
        "正文": "",
        "技能包": 技能包,
    }


def 处理存节(技能包, 节标题, 新内容, 老师原话=""):
    技能包库.校验代号(技能包)
    if not str(新内容).strip():
        raise ValueError("新内容不能为空。要整段删掉的话，请先把这句话写进"
                         "「老师原话」里，我们再单独处理。")
    路径, 原文 = 读原始(技能包)
    前置行们, 节们, 有末换行 = 拆节(原文)
    标题们 = [节["标题"] for 节 in 节们]
    要改 = str(节标题).strip()
    if 要改 not in 标题们:
        raise ValueError("这份技能包里没有叫「" + 要改 + "」的一段。它有："
                         + "、".join(标题们))
    新全文 = 拼回(前置行们, 节们, 改标题=要改, 新内容=新内容, 有末换行=有末换行)
    技能包库.保存技能包(配置.取目录("技能包"), 技能包, 新全文)
    _评定.记校订(技能包, 要改, 老师原话)
    审计.记一笔("存技能包节", {"技能包": 技能包, "节": 要改}, 成功=True)
    return {
        "提示": "「" + 要改 + "」这段已改回去，老师的话也记下了。"
                "改前那一版在 技能包\\" + 技能包 + "\\_历史\\ 里。",
        "正文": "",
        "条目": [],
    }


注册表.登记(
    代号="技能包校订",
    标题="技能包校订（逐段看）",
    说明="把某份技能包按 ## 拆成一段一段，交给老师逐段过（教师审核闭环）",
    参数=[
        {"代号": "技能包", "标签": "要校订哪一份技能包", "类型": "text", "必填": True,
         "可选项来源": "技能包"},
    ],
    处理函数=处理看节,
)

注册表.登记(
    代号="存技能包节",
    标题="存技能包节",
    说明="把老师改过的一段存回技能包（存前自动备份，改坏可恢复）",
    参数=[
        {"代号": "技能包", "标签": "改哪一份技能包", "类型": "text", "必填": True,
         "可选项来源": "技能包"},
        {"代号": "节标题", "标签": "改哪一段（就是上面列出的那段标题）",
         "类型": "text", "必填": True, "示例": "例如：核心自述"},
        {"代号": "新内容", "标签": "老师改后的这一段", "类型": "textarea", "必填": True},
        {"代号": "老师原话", "标签": "老师为什么这么改（原话，不要润色）",
         "类型": "textarea", "必填": False},
    ],
    处理函数=处理存节,
)
